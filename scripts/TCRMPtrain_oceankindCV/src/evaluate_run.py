def fmt_num(x, nd=3):
    """Format a score to nd decimals; None reads N/A and a non-number is shown as text."""
    if x is None:
        return 'N/A'
    try:
        return f'{float(x):.{nd}f}'
    except (TypeError, ValueError):
        return str(x)


def fmt_dur(secs):
    """Format seconds as 12s, 3m 4s or 1h 2m 3s; None reads N/A."""
    if secs is None:
        return 'N/A'
    s = int(secs)
    if s < 60:
        return f'{s}s'
    m, s = divmod(s, 60)
    if m < 60:
        return f'{m}m {s}s'
    h, m = divmod(m, 60)
    return f'{h}h {m}m {s}s'


