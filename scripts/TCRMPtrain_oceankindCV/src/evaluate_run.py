def _parse_label_line(fields, img_w, img_h):
    """Turn one split label line into (class_id, shape, pixel points).

    Parameters:
        fields: the whitespace-split tokens of one line.
        img_w, img_h: image size in pixels, used to scale normalized coordinates.
    Returns:
        (class_id, LABEL_SHAPE_BOX, [[x0, y0], [x1, y1]]) for a five-field
        detection line, or (class_id, LABEL_SHAPE_POLYGON, Nx2 array) for a
        segmentation line.
    Raises:
        ValueError naming the problem for any line that is not a label.
    """
    try:
        class_id = int(fields[0])
    except ValueError as exc:
        raise ValueError(f'class id {fields[0]!r} is not an integer') from exc
    if class_id < 0:
        raise ValueError(f'class id {class_id} is negative')
    try:
        coords = np.array([float(x) for x in fields[1:]], dtype=np.float64)
    except ValueError as exc:
        raise ValueError(f'a coordinate is not a number: {exc}') from exc
    n = len(coords)
    if n != LABEL_BOX_COORDS and (n < LABEL_POLYGON_MIN_COORDS or n % 2 != 0):
        raise ValueError(
            f'expected {LABEL_BOX_COORDS} box coordinates or an even count of at least '
            f'{LABEL_POLYGON_MIN_COORDS} polygon coordinates, got {n}'
        )
    if not np.all(np.isfinite(coords)) or coords.min() < 0.0 or coords.max() > 1.0:
        raise ValueError('coordinates must be normalized to the 0..1 range')
    if n == LABEL_BOX_COORDS:
        cx, cy, bw, bh = coords
        if bw <= 0.0 or bh <= 0.0:
            raise ValueError('box has no area')
        corners = np.array([[(cx - bw / 2) * img_w, (cy - bh / 2) * img_h],
                            [(cx + bw / 2) * img_w, (cy + bh / 2) * img_h]])
        return class_id, LABEL_SHAPE_BOX, corners
    poly = coords.reshape(-1, 2)
    poly[:, 0] *= img_w
    poly[:, 1] *= img_h
    return class_id, LABEL_SHAPE_POLYGON, poly


def parse_yolo_label_file(label_path, img_w, img_h):
    """Read a YOLO label file in the detection shape or the segmentation shape.

    A detection line is `class cx cy w h` (normalized centre and size); a
    segmentation line is `class` followed by an even count of at least six
    normalized x,y values. Blank lines are ignored. A missing file means an
    image with no objects, the YOLO convention.

    Parameters:
        label_path: path to the .txt label file.
        img_w, img_h: image size in pixels.
    Returns:
        dict with 'instances', a list of (class_id, shape, pixel points) in
        file order, and 'skipped', a list of (line number, reason) for every
        line that could not be read as a label.
    Raises:
        ValueError when img_w or img_h is not a positive number.
    """
    if not (isinstance(img_w, (int, float)) and isinstance(img_h, (int, float))) or img_w <= 0 or img_h <= 0:
        raise ValueError(f'image size must be positive, got {img_w!r} x {img_h!r} for {label_path}')
    parsed = {'instances': [], 'skipped': []}
    if not os.path.isfile(label_path):
        return parsed
    with open(label_path, encoding='utf-8', errors='replace') as fh:
        for line_no, line in enumerate(fh, start=1):
            if len(line) > LABEL_MAX_LINE_CHARS:
                parsed['skipped'].append((line_no, f'line exceeds {LABEL_MAX_LINE_CHARS} characters'))
                continue
            fields = line.split()
            if not fields:
                continue
            try:
                parsed['instances'].append(_parse_label_line(fields, img_w, img_h))
            except ValueError as exc:
                parsed['skipped'].append((line_no, str(exc)))
    return parsed


def _draw_ground_truth(draw, instances):
    """Draw every ground-truth instance in the brand pink, boxes as rectangles.

    Parameters:
        draw: a PIL ImageDraw in RGBA mode.
        instances: the 'instances' list from parse_yolo_label_file.
    Returns:
        None.
    """
    for _class_id, shape, pts in instances:
        if shape == LABEL_SHAPE_BOX:
            (x0, y0), (x1, y1) = pts.tolist()
            draw.rectangle([x0, y0, x1, y1], fill=GT_FILL_RGBA, outline=GT_OUTLINE_RGBA)
        else:
            draw.polygon([tuple(p) for p in pts.tolist()], fill=GT_FILL_RGBA, outline=GT_OUTLINE_RGBA)


def _render_side_by_side_preview(image_path, label_path, model, conf, iou, imgsz, out_path):
    """Composite one JPG: left, the image with its ground-truth boxes or
    outlines; right, the image with the model's predictions.

    Parameters:
        image_path: the source image.
        label_path: its YOLO label file (box or polygon lines).
        model: a loaded ultralytics model.
        conf, iou, imgsz: prediction settings.
        out_path: where to write the composite.
    Returns:
        dict with 'source', 'overlay', 'filename', 'n_gt', 'n_pred', or None
        when the image cannot be opened.
    """
    try:
        from PIL import Image, ImageDraw, ImageFont
    except Exception as e:
        print(f'[eval] PIL import failed: {e}')
        return None

    try:
        img = Image.open(image_path).convert('RGB')
    except Exception as e:
        print(f'[eval] failed to open {image_path}: {e}')
        return None
    w, h = img.size

    # GT side
    gt_img = img.copy()
    gt_draw = ImageDraw.Draw(gt_img, 'RGBA')
    labels = parse_yolo_label_file(label_path, w, h)
    for line_no, reason in labels['skipped']:
        print(f'[eval] {label_path}: skipped line {line_no}: {reason}')
    gts = labels['instances']
    _draw_ground_truth(gt_draw, gts)

    # Pred side
    pr_img = img.copy()
    n_pred = 0
    try:
        results = model.predict(image_path, conf=conf, iou=iou, imgsz=imgsz,
                                save=False, verbose=False)
        if results:
            r = results[0]
            arr = r.plot()  # BGR numpy with model overlays
            pr_img = Image.fromarray(arr[..., ::-1])
            n_pred = int(len(r.masks)) if r.masks is not None else int(len(r.boxes)) if r.boxes is not None else 0
    except Exception as e:
        print(f'[eval] predict failed for {image_path}: {e}')

    # Resize to same height, place side by side
    target_h = 720
    scale_g = target_h / h
    gt_r = gt_img.resize((int(w * scale_g), target_h))
    pr_r = pr_img.resize((int(pr_img.size[0] * (target_h / pr_img.size[1])), target_h))

    label_band = 36
    composite_w = gt_r.size[0] + pr_r.size[0] + 10
    composite_h = target_h + label_band
    composite = Image.new('RGB', (composite_w, composite_h), 'white')
    composite.paste(gt_r, (0, label_band))
    composite.paste(pr_r, (gt_r.size[0] + 10, label_band))

    # Draw captions
    draw = ImageDraw.Draw(composite)
    try:
        font = ImageFont.truetype('/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf', 18)
    except OSError:
        font = ImageFont.load_default()  # the DejaVu face is absent; PIL's built-in face is legible
    draw.rectangle([0, 0, gt_r.size[0], label_band], fill=(226, 0, 116))
    draw.text((8, 6),
              f'Ground truth: {count_noun(len(gts), "human-drawn instance")}',
              fill='white', font=font)
    draw.rectangle([gt_r.size[0] + 10, 0, composite_w, label_band], fill=(40, 40, 40))
    draw.text((gt_r.size[0] + 18, 6),
              f'Model prediction at confidence >= {conf:.2f}: {count_noun(n_pred, "detection")}',
              fill='white', font=font)

    composite.save(out_path, quality=88)
    return {
        'source': image_path,
        'overlay': out_path,
        'filename': os.path.basename(image_path),
        'n_gt': len(gts),
        'n_pred': n_pred,
    }


def preview_conf_of(args):
    """The confidence the report's sample images were drawn at.

    Parameters:
        args: the parsed command line, or any namespace the report builders
            are handed. A namespace built before --preview_conf existed
            (2026-09-15) carries none; those previews were drawn at the
            then-default 0.25, which is PREVIEW_CONF_DEFAULT, so reading it
            back reports what the reader is actually looking at.
    Returns:
        The display threshold as a float.

    Example:
        preview_conf_of(argparse.Namespace(preview_conf=0.4)) -> 0.4
    """
    return float(getattr(args, 'preview_conf', PREVIEW_CONF_DEFAULT))


def render_previews(model, dataset_dir, split, out_dir, count, conf, iou, imgsz):
    """Render up to `count` side-by-side previews from the evaluated split; return their caption metadata.

    conf here is the DISPLAY threshold (preview_conf_of(args)), not the
    cut-off the score was measured with: a prediction pass keeps up to 300
    boxes, so drawing the samples at the measurement threshold would bury the
    frame under near-zero detections.
    """
    preview_dir = os.path.join(out_dir, 'previews')
    os.makedirs(preview_dir, exist_ok=True)

    split_dir = 'test' if split == 'test' else ('valid' if split == 'val' else 'train')
    img_dir = os.path.join(dataset_dir, split_dir, 'images')
    lbl_dir = os.path.join(dataset_dir, split_dir, 'labels')
    if not os.path.isdir(img_dir):
        return []

    # Every type the scorer opens is a candidate (_image_suffixes), so a
    # split held in WebP or TIFF is sampled instead of producing no previews
    # at all. Anything that is not a readable file is skipped.
    suffixes = _image_suffixes()
    try:
        with os.scandir(img_dir) as entries:
            candidates = sorted(e.name for e in entries
                                if e.name.lower().endswith(suffixes) and e.is_file())
    except OSError as exc:
        raise OSError(f'cannot list {img_dir} for preview images: {exc}') from exc
    if not candidates:
        return []

    random.seed(0)
    sample = candidates if len(candidates) <= count else random.sample(candidates, count)
    sample.sort()

    saved = []
    for fn in sample:
        src = os.path.join(img_dir, fn)
        stem = os.path.splitext(fn)[0]
        lbl = os.path.join(lbl_dir, stem + '.txt')
        dst = os.path.join(preview_dir, stem + '_sbs.jpg')
        try:
            info = _render_side_by_side_preview(src, lbl, model, conf, iou, imgsz, dst)
            if info:
                saved.append(info)
        except Exception as e:
            print(f'[eval] preview failed for {fn}: {e}')
    return saved


