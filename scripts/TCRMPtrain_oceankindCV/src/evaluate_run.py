def _validate_main_inputs(args):
    """Refuse a run or dataset folder that does not exist before any work starts.

    Parameters:
        args: the parsed command line.
    Raises:
        FileNotFoundError naming the flag and the path.
    """
    for flag, path in (('run_dir', args.run_dir), ('dataset_dir', args.dataset_dir)):
        if not os.path.isdir(path):
            raise FileNotFoundError(f'--{flag} {path} is not a folder')


def _export_pdf_copy(pdf_path, export_dir, run_dir):
    """Copy the PDF into export_dir as <run name>_report.pdf.

    Parameters:
        pdf_path: the verified PDF.
        export_dir: the folder asked for with --pdf_export_dir (created if absent).
        run_dir: the evaluated run, whose basename names the copy.
    Returns:
        The copy's path.
    Raises:
        OSError naming both paths when the folder cannot be made or the copy fails.
    """
    dest = os.path.join(export_dir, f'{_run_name_of(run_dir)}_report.pdf')
    try:
        os.makedirs(export_dir, exist_ok=True)
        shutil.copy2(pdf_path, dest)
    except OSError as exc:
        raise OSError(f'copying {pdf_path} to {dest} failed: {exc}') from exc
    return dest


def main():
    """Evaluate one run end to end and return the process exit code.

    Order of writes, so a late failure never loses the numbers: report.md
    and metrics.json first, then the ledger row, then report.html and the
    PDF, then the optional export copy, then the model card beside best.pt
    (a card problem is one printed line and never changes the exit code).
    A failed ledger row, PDF or export
    copy is printed with its traceback, the outputs that were written are
    listed, and the code is EXIT_OUTPUT_MISSING; EXIT_OK only when everything
    asked for exists.

    Returns:
        EXIT_OK or EXIT_OUTPUT_MISSING.
    Raises:
        FileNotFoundError when --run_dir or --dataset_dir is not a folder,
        and whatever validation or metric extraction raises before the
        first output is written.
    """
    args = arg_parse()
    apply_gpu_device_override(args)
    _validate_main_inputs(args)
    os.makedirs(args.out_dir, exist_ok=True)

    print(f'[eval] run_dir={args.run_dir}')
    print(f'[eval] dataset_dir={args.dataset_dir}')
    print(f'[eval] split={args.split} imgsz={args.imgsz} conf={args.conf} iou={args.iou} '
          f'preview_conf={preview_conf_of(args)}')

    data_yaml = _resolve_data_yaml(args.dataset_dir, args.split)
    set_names_full(names_full_from_data_yaml(data_yaml))
    print(f'[eval] {len(_names_full_cache)} class names from the dataset at {data_yaml}')
    set_subject_noun(subject_noun_for_dataset(args.dataset_dir, data_yaml))
    subject_singular, subject_plural = subject_nouns()
    print(f'[eval] the report names one scored thing: {subject_singular}, '
          f'plural {subject_plural}')

    val_out = run_val(args)
    metrics = extract_metrics(val_out)
    ctx = gather_context(args.run_dir, args.dataset_dir)

    # The samples are DRAWN at the display threshold while the score above was
    # MEASURED at args.conf; one number cannot do both jobs.
    previews = render_previews(
        val_out['model'], args.dataset_dir, args.split,
        args.out_dir, args.preview_count, preview_conf_of(args), args.iou, args.imgsz,
    )

    report_md = build_report_md(metrics, ctx, previews, args)
    md_path = os.path.join(args.out_dir, 'report.md')
    json_path = os.path.join(args.out_dir, 'metrics.json')
    pdf_path = os.path.join(args.out_dir, 'report.pdf')
    with open(md_path, 'w', encoding='utf-8') as f:
        f.write(report_md)
    with open(json_path, 'w', encoding='utf-8') as f:
        # subject_noun records the word this report used for one scored thing,
        # so two evaluations can be compared from their JSON alone without
        # opening the PDFs.
        json.dump({'metrics': metrics, 'context': ctx, 'previews': previews,
                   'args': vars(args), 'generated_at': ast_now(),
                   'subject_noun': [subject_singular, subject_plural]},
                  f, indent=2, default=str)
    written = [md_path, json_path]
    failures = []

    if args.rounds_dir:
        rounds_csv = os.path.join(args.rounds_dir, 'rounds.csv')
        try:
            row = append_round_row(args.rounds_dir, args.run_dir, metrics, args.dataset_dir,
                                   conf=args.conf, iou=args.iou, imgsz=args.imgsz)
            print(f"[eval] rounds ledger updated: round={row['round']} "
                  f"family={row['metric_family']} split_pinned={row['split_pinned']} "
                  f"gate_map={row['gate_map']} gate_class={row['gate_class']} "
                  f"gate_recall={row['gate_recall']} "
                  f"measured_at conf={row['conf']} iou={row['iou']} imgsz={row['imgsz']}")
            written.append(rounds_csv)
        except Exception as exc:
            traceback.print_exc()
            failures.append(f'rounds ledger row in {rounds_csv} not written: {exc}')

    print('[eval] building PDF...')
    pdf_written = False
    try:
        build_pdf(metrics, ctx, previews, args, pdf_path)
        written.append(pdf_path)
        pdf_written = True
    except Exception as exc:
        traceback.print_exc()
        failures.append(f'PDF {pdf_path} not produced: {exc}')

    if pdf_written and args.pdf_export_dir:
        try:
            dest = _export_pdf_copy(pdf_path, args.pdf_export_dir, ctx['run_dir'])
            print(f'[eval] PDF also exported to {dest}')
            written.append(dest)
        except OSError as exc:
            failures.append(f'PDF export copy not made: {exc}')

    # Last, so the card's record reads this evaluation's metrics.json, report
    # and ledger row from disk.
    try:
        card_path = refresh_model_card(val_out['weights'], metrics, args.split)
    except Exception as exc:  # a card problem never fails the evaluation
        print(f'[eval] card not refreshed: {exc}')
        card_path = None
    if card_path:
        print(f'[eval] model card refreshed: {card_path}')

    print('[eval] written: ' + ', '.join(written))
    if failures:
        print('[eval] FAILED: ' + '; '.join(failures))
        print(f'[eval] exit code {EXIT_OUTPUT_MISSING}: the files listed as written exist; '
              'the ones named as failed do not')
        return EXIT_OUTPUT_MISSING
    print('[eval] done.')
    return EXIT_OK


if __name__ == '__main__':
    try:
        sys.exit(main())
    except Exception:
        traceback.print_exc()
        sys.exit(1)
