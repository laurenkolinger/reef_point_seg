def glossary_rows(family):
    """The glossary in the order it prints, worded for one metric family.

    A detector has no outline curves and no outline scores, so three of the
    rows written for a segmentation run misdescribe it: one names outlines it
    never drew, and two send the reader to a page 4 that holds nothing for it.
    Every other row reads the same for both families, and a segmentation run
    gets GLOSSARY_TABLE unchanged.

    Parameters:
        family: METRIC_FAMILY_MASK or METRIC_FAMILY_BOX.
    Returns:
        list[tuple]: (term, definition, good range, red flag) in report order.
    Raises:
        ValueError when family is neither metric family, because a glossary
        that guessed would tell the reader the wrong thing about the run.

    Example:
        >>> glossary_rows(METRIC_FAMILY_MASK) == GLOSSARY_TABLE
        True
    """
    if family not in METRIC_FAMILIES:
        raise ValueError(f'unknown metric family {family!r}; expected one of {METRIC_FAMILIES}')
    if family == METRIC_FAMILY_MASK:
        return list(GLOSSARY_TABLE)
    return [DETECTOR_GLOSSARY_ROWS.get(row[0], row) for row in GLOSSARY_TABLE]


