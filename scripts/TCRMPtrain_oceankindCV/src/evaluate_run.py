# Per-class bar chart geometry: inches per class row, the height range that
# keeps the chart on its page beside the axis notes and callout, the width,
# and the label size range as rows get denser.
PER_CLASS_BAR_ROW_IN = 0.115
PER_CLASS_BAR_MIN_HEIGHT_IN = 1.2
PER_CLASS_BAR_MAX_HEIGHT_IN = 6.2
PER_CLASS_BAR_MARGIN_IN = 0.8
PER_CLASS_BAR_WIDTH_IN = 6.5
PER_CLASS_BAR_LABEL_PT_MAX = 8.0
PER_CLASS_BAR_LABEL_PT_MIN = 4.0
# Fraction of a row's height a label may fill so neighbouring labels stay apart.
PER_CLASS_BAR_LABEL_FILL = 0.85
POINTS_PER_INCH = 72


def _per_class_bar_geometry(n_classes):
    """Figure height and label size for a bar chart of n_classes rows.

    Parameters:
        n_classes: number of bars.
    Returns:
        (height_in, label_pt): the figure height in inches, bounded by
        PER_CLASS_BAR_MIN_HEIGHT_IN and PER_CLASS_BAR_MAX_HEIGHT_IN, and the
        label font size in points that fits one row at that height.
    """
    height_in = min(PER_CLASS_BAR_MAX_HEIGHT_IN,
                    max(PER_CLASS_BAR_MIN_HEIGHT_IN, PER_CLASS_BAR_ROW_IN * n_classes + PER_CLASS_BAR_MARGIN_IN))
    row_pt = (height_in - PER_CLASS_BAR_MARGIN_IN) / max(1, n_classes) * POINTS_PER_INCH
    label_pt = max(PER_CLASS_BAR_LABEL_PT_MIN, min(PER_CLASS_BAR_LABEL_PT_MAX, row_pt * PER_CLASS_BAR_LABEL_FILL))
    return height_in, label_pt


def _per_class_bar_labels(class_tokens):
    """Axis labels for the bar chart: each class's full name, italic when it is a binomial.

    Parameters:
        class_tokens: class tokens from data.yaml, in bar order.
    Returns:
        list of (label, italic) tuples, e.g. ('Scolymia cubensis', True), ('sand', False).
    """
    labels = []
    for token in class_tokens:
        full = class_full_name(token)
        labels.append((full, BINOMIAL_NAME_RE.fullmatch(full) is not None))
    return labels


def _plot_per_class_bar(per_class_data, out_path, metric_key):
    """Horizontal bar chart of one per-class score, sorted descending, pink palette.

    The figure grows with the class count (one row per class) up to the
    page bound, the labels shrink to fit their rows, and each bar is
    labelled with the species' full name (italic for a binomial), the same
    name the table shows.

    Parameters:
        per_class_data: metrics['per_class'], class name -> score dict.
        out_path: PNG path to write.
        metric_key: the per-class key to chart, e.g. 'box_map50_95'.
    Returns:
        out_path, or None when no class carries that key.
    Raises:
        ValueError when metric_key does not start with a metric family.
    """
    family = metric_key.split('_', 1)[0]
    if family not in METRIC_FAMILIES:
        raise ValueError(f'metric_key {metric_key!r} does not start with a metric family')
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    items = []
    for cls, d in per_class_data.items():
        v = d.get(metric_key)
        if v is None:
            continue
        items.append((cls, float(v)))
    if not items:
        return None
    items.sort(key=lambda x: x[1], reverse=True)
    labels = _per_class_bar_labels([i[0] for i in items])
    values = [i[1] for i in items]

    h, label_pt = _per_class_bar_geometry(len(items))
    fig, ax = plt.subplots(figsize=(PER_CLASS_BAR_WIDTH_IN, h), dpi=130)
    y_pos = range(len(items))
    ax.barh(list(y_pos), values, color='#E20074', alpha=0.85, edgecolor='#8a003f')
    ax.set_yticks(list(y_pos))
    ax.set_yticklabels([text for text, _italic in labels], fontsize=label_pt)
    for (_text, italic), tick in zip(labels, ax.get_yticklabels()):
        if italic:
            tick.set_fontstyle('italic')
    ax.invert_yaxis()
    ax.set_xlabel(f'mAP50-95 ({FAMILY_LABELS[family]})', fontsize=8)
    ax.set_xlim(0, max(1.0, max(values) * 1.15))
    ax.tick_params(axis='x', labelsize=7)
    ax.grid(axis='x', alpha=0.3, linewidth=0.4)
    for i, v in enumerate(values):
        ax.text(v + 0.01, i, f'{v:.3f}', fontsize=min(7, label_pt), va='center', color='#222')
    for spine in ('top', 'right'):
        ax.spines[spine].set_visible(False)
    plt.tight_layout(pad=0.4)
    fig.savefig(out_path, bbox_inches='tight', pad_inches=0.08)
    plt.close(fig)
    return out_path


def _plot_training_history(results_csv_path, out_path):
    """2x2 grid: box/seg/cls/dfl losses, train vs val on each panel."""
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    import numpy as np

    if not os.path.isfile(results_csv_path):
        return None

    with open(results_csv_path) as f:
        rows = list(_csv.reader(f))
    if len(rows) < 2:
        return None
    hdr = [h.strip() for h in rows[0]]
    data = rows[1:]

    def col(name):
        """Column `name` of results.csv as a float array, NaN where a cell is blank; None when the column is missing."""
        if name not in hdr:
            return None
        idx = hdr.index(name)
        out = []
        for r in data:
            if idx >= len(r):
                out.append(np.nan); continue
            try:
                out.append(float(r[idx]))
            except ValueError:
                out.append(np.nan)  # a blank or non-numeric cell leaves a gap in the curve
        return np.array(out)

    epochs = col('epoch')
    if epochs is None:
        epochs = np.arange(len(data))

    panels = [
        ('box',  'train/box_loss',  'val/box_loss',  'Box loss'),
        ('seg',  'train/seg_loss',  'val/seg_loss',  'Seg loss'),
        ('cls',  'train/cls_loss',  'val/cls_loss',  'Cls loss'),
        ('dfl',  'train/dfl_loss',  'val/dfl_loss',  'DFL loss'),
    ]

    fig, axes = plt.subplots(2, 2, figsize=(7.4, 4.8), dpi=130)
    for ax, (_k, tc, vc, title) in zip(axes.ravel(), panels):
        t = col(tc)
        v = col(vc)
        if t is not None:
            ax.plot(epochs, t, color='#E20074', lw=1.2, label='train')
        if v is not None:
            ax.plot(epochs, v, color='#333', lw=1.0, label='val', linestyle='--')
        ax.set_title(title, fontsize=9, fontweight='bold')
        ax.tick_params(labelsize=7)
        ax.grid(alpha=0.25, linewidth=0.4)
        if t is None and v is None:
            # A detector logs no seg loss; say so instead of leaving a bare panel.
            ax.text(0.5, 0.5, 'not tracked for this run', ha='center', va='center',
                    fontsize=8, color='#666', transform=ax.transAxes)
        else:
            ax.legend(fontsize=7, loc='upper right')
        for spine in ('top', 'right'):
            ax.spines[spine].set_visible(False)
    fig.tight_layout(pad=0.5)
    fig.savefig(out_path, bbox_inches='tight', pad_inches=0.08)
    plt.close(fig)
    return out_path


def _interpret_convergence(results_csv_path):
    """Plain-language commentary on how training converged, written as
    complete sentences so the paragraph can be pasted into the PDF as-is.

    Always spells out the terms 'training loss' and 'validation loss' (the
    internal error scores the optimizer drives down), so the reader does
    not need to know what the loss curves mean coming in.

    Parameters:
        results_csv_path: the run's results.csv.
    Returns:
        The commentary, or '' when the file is missing or its loss columns
        cannot be read (the reason is printed).
    """
    if not os.path.isfile(results_csv_path):
        return ''
    try:
        with open(results_csv_path) as f:
            rows = list(_csv.reader(f))
        if len(rows) < 6:
            n = max(0, len(rows) - 1)
            return (
                f"Training ran for only {n} epochs, which is too few to draw "
                "firm conclusions about convergence or overfitting."
            )
        hdr = [h.strip() for h in rows[0]]
        data = rows[1:]
        def col(name):
            """Column `name` of results.csv as a float array, NaN where a cell is blank; None when the column is missing."""
            if name not in hdr: return None
            idx = hdr.index(name)
            return np.array([float(r[idx]) if idx < len(r) and r[idx].strip() else np.nan
                             for r in data])
        vbox = col('val/box_loss')
        tbox = col('train/box_loss')
        n = len(data)
        if vbox is None or tbox is None:
            return (
                f"Training ran for {n} epochs, but the loss columns were not "
                "found in results.csv, so the convergence behavior cannot be "
                "described here."
            )
        final = np.nanmin(vbox[-10:]) if n >= 10 else np.nanmin(vbox)
        converge_ep = n
        for i, v in enumerate(vbox):
            if not np.isnan(v) and v <= final * 1.02:
                converge_ep = i + 1
                break

        tail = max(5, n // 5)
        overfit = False
        if n >= tail * 2:
            tr_slope = np.nanmean(tbox[-tail:]) - np.nanmean(tbox[-tail*2:-tail])
            va_slope = np.nanmean(vbox[-tail:]) - np.nanmean(vbox[-tail*2:-tail])
            overfit = (tr_slope < -0.002 and va_slope > 0.002)

        sent1 = (
            f"The training loss and validation loss both fell through "
            f"epoch {n} and reached their plateau near epoch "
            f"{converge_ep}, which is where the model stopped learning new "
            "generalizable features."
        )
        if overfit:
            sent2 = (
                f"Over the final {tail} epochs, the training loss kept "
                "dropping while the validation loss rose slightly, which is "
                "the classic symptom of overfitting: the model is starting "
                "to memorize the training images rather than learn patterns "
                "that transfer to new data."
            )
            sent3 = (
                "Because the checkpoint saved as 'best.pt' is picked from "
                "the best validation epoch, the saved weights predate this "
                "overfit period and should still generalize, but future "
                "training runs would benefit from stopping earlier."
            )
        else:
            sent2 = (
                f"Across the final {tail} epochs there was no sign of "
                "overfitting: the validation loss did not rise while the "
                "training loss continued to fall, which means the model was "
                "still learning generalizable patterns rather than "
                "memorizing the training set."
            )
            sent3 = (
                "The 'best.pt' checkpoint chosen by the trainer corresponds "
                "to an epoch where validation performance had plateaued, so "
                "it is a reasonable representative of the run's quality."
            )
        return ' '.join([sent1, sent2, sent3])
    except (OSError, _csv.Error, ValueError, IndexError) as exc:
        print(f'[eval] convergence commentary skipped, {results_csv_path} could not be '
              f'read as loss columns: {exc}')
        return ''


