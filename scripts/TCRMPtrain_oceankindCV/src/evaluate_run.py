def _render_training(metrics, ctx, args, figures, page_num):
    """HTML for the training page: hyperparameters, loss curves and convergence commentary.

    Parameters:
        metrics: extract_metrics() output; its metric family decides which
            losses the page says were tracked.
        ctx: gather_context() output (train_args, run_dir).
        args: parsed CLI arguments.
        figures: dict from _collect_figures.
        page_num: the page this section prints on, from _plan_pages.
    Returns:
        One <section class="page"> HTML string.
    """
    ta = ctx.get('train_args', {}) or {}
    if metric_family(metrics) == METRIC_FAMILY_MASK:
        losses_sentence = (
            "Four losses are tracked: box (how well bounding rectangles fit), "
            "seg (how well masks fit), cls (how well the class label is "
            "predicted), and dfl (a helper loss that sharpens box edges)."
        )
    else:
        losses_sentence = (
            "Three losses are tracked: box (how well bounding rectangles fit), "
            "cls (how well the class label is predicted), and dfl (a helper "
            "loss that sharpens box edges). This run predicts boxes only, so "
            "it has no segmentation loss."
        )
