#!/usr/bin/env python3
"""Evaluate a trained Ultralytics run (segmentation or detection) and produce
a dense, cheatsheet-style evaluation PDF plus JSON and Markdown.

Invoked by the orchestrator's step 7. Consumes:
    --run_dir    path to a directory containing weights/best.pt (typically
                 {step6_dir}/runs/<run_name>/)
    --dataset_dir   the split dataset dir from step 6 ({step6_dir}/dataset).
                 Its data.yaml may carry names_full, the full species name per
                 class id, written when the staged dataset came with a names
                 table; those names win over the module's code registry. It
                 may also carry subject, the singular and plural noun the
                 report's explanations use for one scored thing; without it
                 the explanations use a neutral noun that is true of any
                 subject a run is trained on.
    --out_dir    where to write evaluation outputs (typically {step7_dir})
    --split      test | val | train
    --imgsz / --batch / --conf / --iou / --preview_count
    --preview_conf  the confidence the sample images are DRAWN at (a display
                 threshold, 0.25 by default); --conf is the lower cut-off the
                 SCORE is measured with, and the two are never the same job
    --pdf_export_dir  optional extra dir to copy the PDF to
    --rounds_dir      optional ledger folder; one row per evaluated run

Emits (inside --out_dir):
    metrics.json          machine-readable numbers
    report.md             markdown version of the report
    report.html           the PDF's source with the stylesheet inlined, kept
                          so a page can be inspected in a browser
    report.pdf            a multi-page PDF cheatsheet (fixed per-page layout)
    previews/             rendered overlay images used in the PDF
    val_run/              ultralytics validation output (curves, matrices)

Refreshes (beside the evaluated weights, test split and best.pt only):
    best.pt.card.md       the model card's record rebuilt from disk (scores,
                          report link, checksum) plus the best confidence

The PDF is printed by headless Chrome (CHROME_BINARY_DEFAULT; the
TCRMP_CHROME_BINARY environment variable points at another Chrome). The
engine changed from WeasyPrint on 2026-09-04 because that library was
installed nowhere on the box, and the PDF outline sidebar it produced is not
generated by Chrome's print path, so the report has no bookmarks. Chrome
exits 0 even when it fails, so the PDF is verified by existence, size and
its first bytes before the run counts as done.

Exit code: EXIT_OK (0) when every requested output exists;
EXIT_OUTPUT_MISSING (2) when report.md and metrics.json were written but
the PDF, the ledger row or the export copy was not (the console says
which); 1 on any other error.

Page layout is fixed for a given class count and preview count, so two
reports of the same model compare page for page. Every page title, the
footer "p. N / M" and the table of contents on the cover come from the same
page plan (_plan_pages); nothing is hardcoded.

    Page 1     Cover sheet + top-line cheatsheet + TOC
    Page 2     Training history (hyperparams + loss curves)
    Page 3     Box metrics cheatsheet
    Page 4     Mask metrics cheatsheet (a detector's page says why it is empty)
    Page 5     Per-class breakdown (bar chart + strongest/weakest callout)
    Page 6+    Per-class table, PER_CLASS_ROWS_PER_PAGE rows per page with
               the header repeated, absent classes last (59 classes: 2 pages)
    Next       Confusion matrix (normalized + absolute)
    Next       Prediction samples, SAMPLES_PER_PAGE per page, GT vs prediction
    Last       Glossary cheatsheet + provenance
"""

