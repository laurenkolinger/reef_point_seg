# ─────────────────────────────────────────────────────────────────────────
# The subject noun: what the explanatory prose calls one scored thing
#
# Every explanation in this module was written for TCRMP coral photographs
# and said "coral" outright, so the first detector trained on something else
# (the 34-class reef fish photo set, evaluated 2026-09-15 02:43 AST) was
# handed a ten-page report that called its fish corals 42 times over.
#
# The default noun is neutral rather than inferred from the class names. The
# module's label registry at supporting_data/master_codes.csv does not carry
# every class the coral training set names (8 of its 59 species are missing
# from it), so a "do these class names look like corals" test would have to
# be a majority vote, and a majority vote gets a mixed or newly-named dataset
# wrong in silence, which is this same bug in a form nobody notices. A noun
# that is true of a coral, a fish and a sponge alike is never wrong, and the
# report still names the real species in the per-class table, the bar chart
# and the confusion matrix. A dataset that wants its own word declares it in
# its data.yaml and subject_noun_from_data_yaml reads it.
#
# Where a declaration survives: a split dataset is written from scratch on
# every build, so a subject key added to the split's own data.yaml is erased
# the next time the dataset is rebuilt. subject_noun_for_dataset therefore
# also reads the staged source that split_manifest.json records, which no
# rebuild rewrites, and the split's own declaration still wins when it has
# one. A dataset folder whose build record names no source (the segmentation
# splitter writes none) can only declare a noun in the split's data.yaml
# today, so those reports read "object" until its builder carries the key
# through.
#
# Mechanism: the prose constants below carry {subject} and {subjects}, and
# every builder that renders them ends with fill_subject. _assemble_report_html
# fills the finished document too, so prose added later cannot reach a reader
# with a placeholder still in it.
# ─────────────────────────────────────────────────────────────────────────

# (singular, plural) the prose uses when the dataset declares nothing.
SUBJECT_NOUN_DEFAULT = ('object', 'objects')

# The optional data.yaml key that declares a dataset's own noun, and the two
# forms it must carry.
SUBJECT_KEY = 'subject'
SUBJECT_FORM_KEYS = ('singular', 'plural')

# A declared noun is written straight into markdown and into HTML, so it is
# held to plain lowercase words: nothing that could open a tag or a markdown
# span, and nothing long enough to break a report sentence.
SUBJECT_NOUN_RE = re.compile(r'[a-z]+(?:[ -][a-z]+)*')
SUBJECT_NOUN_MAX_CHARS = 40

# The placeholders the prose constants carry.
SUBJECT_SINGULAR_PLACEHOLDER = '{subject}'
SUBJECT_PLURAL_PLACEHOLDER = '{subjects}'

# Set once per evaluation from the evaluated dataset, read by fill_subject.
_subject_nouns = SUBJECT_NOUN_DEFAULT


def subject_nouns():
    """The (singular, plural) noun the report calls one scored thing.

    Returns:
        tuple[str, str]: SUBJECT_NOUN_DEFAULT until set_subject_noun changes it.

    Example:
        >>> subject_nouns()
        ('object', 'objects')
    """
    return _subject_nouns


def _validated_noun(value, form_name):
    """One checked noun form.

    Parameters:
        value: the raw value read from a dataset or passed by a caller.
        form_name: 'singular' or 'plural', named in every error.
    Returns:
        The stripped word.
    Raises:
        ValueError when the value is not a plain lowercase word of at most
        SUBJECT_NOUN_MAX_CHARS characters.
    """
    if not isinstance(value, str):
        raise ValueError(f'the {form_name} subject noun must be a string, '
                         f'got {type(value).__name__}')
    word = value.strip()
    if not word:
        raise ValueError(f'the {form_name} subject noun is blank')
    if len(word) > SUBJECT_NOUN_MAX_CHARS:
        raise ValueError(f'the {form_name} subject noun is {len(word)} characters, longer than '
                         f'the {SUBJECT_NOUN_MAX_CHARS} a report sentence can carry')
    if not SUBJECT_NOUN_RE.fullmatch(word):
        raise ValueError(f'the {form_name} subject noun {word!r} is not a plain lowercase word; '
                         'the noun is written into markdown and into HTML, so only letters, '
                         'spaces and hyphens are accepted')
    return word


def set_subject_noun(pair):
    """Set the noun every report builder uses for one scored thing.

    Parameters:
        pair: (singular, plural), both plain lowercase words; None restores
            SUBJECT_NOUN_DEFAULT.
    Returns:
        None.
    Raises:
        TypeError when pair is neither a two-item tuple or list nor None.
        ValueError when either form fails _validated_noun.
    """
    global _subject_nouns
    if pair is None:
        _subject_nouns = SUBJECT_NOUN_DEFAULT
        return
    if isinstance(pair, str) or not isinstance(pair, (tuple, list)) or len(pair) != 2:
        raise TypeError(f'set_subject_noun needs a (singular, plural) pair or None, got {pair!r}')
    _subject_nouns = tuple(_validated_noun(form, name)
                           for form, name in zip(pair, SUBJECT_FORM_KEYS))


def subject_noun_from_data_yaml(path):
    """The (singular, plural) noun a dataset declares for its own subjects.

    An evaluated dataset may carry a subject mapping beside its names:

        subject:
          singular: fish
          plural: fish

    Both forms are required. A plural guessed from a singular writes "fishs"
    into every page of a fish report, so the dataset states both or neither.

    Parameters:
        path: the data.yaml of the evaluated split dataset.
    Returns:
        (singular, plural), or None when the dataset declares nothing.
    Raises:
        FileNotFoundError when path is not a file.
        OSError when the file exists but cannot be read.
        yaml.YAMLError when the file is not valid YAML.
        ValueError when the document is not a mapping, or the declared
        subject is not a mapping of two plain lowercase words, naming the
        file and what is wrong with it.
    """
    if not os.path.isfile(path):
        raise FileNotFoundError(f'data.yaml not found at {path}; the dataset declares no subject')
    with open(path, encoding='utf-8') as fh:
        doc = yaml.safe_load(fh)
    if doc is None:
        doc = {}
    if not isinstance(doc, dict):
        raise ValueError(f'{path} does not hold a mapping, so it declares no subject')
    declared = doc.get(SUBJECT_KEY)
    if declared is None:
        return None
    if not isinstance(declared, dict):
        raise ValueError(
            f'{path} key {SUBJECT_KEY} is a {type(declared).__name__}; it must be a mapping '
            f'carrying {SUBJECT_FORM_KEYS[0]} and {SUBJECT_FORM_KEYS[1]}, because a plural '
            'guessed from a singular writes the wrong word into every page'
        )
    missing = [k for k in SUBJECT_FORM_KEYS if k not in declared]
    if missing:
        raise ValueError(f'{path} key {SUBJECT_KEY} lacks {missing}')
    try:
        return tuple(_validated_noun(declared[k], k) for k in SUBJECT_FORM_KEYS)
    except ValueError as exc:
        raise ValueError(f'{path} key {SUBJECT_KEY}: {exc}') from None


def _staged_source_dir(dataset_dir):
    """The staged dataset a split dataset was built from, or None.

    A split dataset's build record names its source; nothing else on disk
    does. An absent, unreadable or sourceless record is not an error here,
    because the report only loses a word by it, so each case is printed and
    read past rather than stopping an evaluation that has its numbers.

    Parameters:
        dataset_dir: the evaluated split dataset folder.
    Returns:
        str: the source folder, when the record names one that is on disk.
        None: otherwise.
    """
    manifest_path = os.path.join(dataset_dir, SPLIT_MANIFEST_NAME)
    if not os.path.isfile(manifest_path):
        return None
    try:
        with open(manifest_path, encoding='utf-8') as fh:
            manifest = json.load(fh)
    except (OSError, json.JSONDecodeError) as exc:
        print(f'[eval] {manifest_path} unreadable, the staged source was not consulted '
              f'for a subject noun: {exc}')
        return None
    if not isinstance(manifest, dict):
        print(f'[eval] {manifest_path} holds no object, so it names no staged source')
        return None
    source = manifest.get(MANIFEST_SOURCE_KEY)
    if not isinstance(source, str) or not source.strip():
        return None
    if not os.path.isdir(source):
        print(f'[eval] the staged source {source} recorded in {manifest_path} is not on disk, '
              'so any subject noun it declares was not read')
        return None
    return source


def subject_noun_for_dataset(dataset_dir, data_yaml):
    """The (singular, plural) noun declared for one evaluated dataset.

    Two files can declare it, and the nearer one wins:

    1. the evaluated split dataset's own data.yaml, and
    2. the data.yaml of the staged dataset it was built from, named by
       SPLIT_MANIFEST_NAME's MANIFEST_SOURCE_KEY.

    The second matters because a split dataset is written from scratch every
    time it is built, so a key added to its data.yaml by hand is erased on the
    next build, while the staged source it came from is never rewritten.

    Parameters:
        dataset_dir: the evaluated split dataset folder.
        data_yaml: that dataset's data.yaml, as _resolve_data_yaml returned it.
    Returns:
        (singular, plural), or None when neither file declares a subject.
    Raises:
        ValueError when either file declares a subject it may not: a
        declaration written badly is refused by name rather than rendered
        into every page of the report.
    """
    declared = subject_noun_from_data_yaml(data_yaml)
    if declared is not None:
        return declared
    source = _staged_source_dir(dataset_dir)
    if source is None:
        return None
    source_yaml = os.path.join(source, 'data.yaml')
    if not os.path.isfile(source_yaml):
        return None
    return subject_noun_from_data_yaml(source_yaml)


def fill_subject(text):
    """Replace the subject placeholders in one string with the run's noun.

    Parameters:
        text: report prose, with or without the placeholders.
    Returns:
        The prose with SUBJECT_PLURAL_PLACEHOLDER and
        SUBJECT_SINGULAR_PLACEHOLDER replaced. Idempotent, so a builder may
        fill its own output and still be assembled into a document that is
        filled again.

    Example:
        >>> fill_subject('every {subject} the model finds')
        'every object the model finds'
    """
    singular, plural = subject_nouns()
    return (text.replace(SUBJECT_PLURAL_PLACEHOLDER, plural)
                .replace(SUBJECT_SINGULAR_PLACEHOLDER, singular))


