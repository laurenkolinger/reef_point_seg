def _image_suffixes():
    """Lowercase filename suffixes, leading dot included, of the image types
    training and validation read.

    The ledger's n_train, n_valid and n_test columns say how much data a round
    was measured on, so the list behind them has to be the one the scorer
    itself uses. Ultralytics validates on every format in its IMG_FORMATS (in
    8.4.38: avif, bmp, dng, heic, heif, jp2, jpeg, jpeg2000, jpg, mpo, png,
    tif, tiff, webp), and a dataset staged from an outside experiment can
    carry any of them. A shorter list kept here would report fewer images than
    were scored: the fish detector's first ledger row, written 2026-09-15
    02:43 AST, recorded 5296 / 1512 / 757 against a dataset of 5300 / 1514 /
    758, short by exactly the 7 WebP images in it.

    The ultralytics import is local so this module still imports where
    ultralytics is absent (the ledger tests exercise append_round_row without
    it). There the detection stager's own IMAGE_EXTS stands in, from
    scripts/TCRMPtrain_oceankindCV/src/detect_dataset.py, which covers every
    type this platform's staging tool writes. No third list is kept here.

    Returns:
        tuple[str, ...]: the suffixes, sorted, each starting with a dot.

    Raises:
        ImportError: when neither list can be imported, since no honest image
            count is possible without one of them.

    Example:
        >>> '.webp' in _image_suffixes()
        True
    """
    try:
        from ultralytics.data.utils import IMG_FORMATS
        formats = IMG_FORMATS
    except ImportError:
        try:
            from detect_dataset import IMAGE_EXTS
        except ImportError as exc:
            raise ImportError(
                'image count needs a list of readable image types, and neither '
                'ultralytics.data.utils.IMG_FORMATS nor detect_dataset.IMAGE_EXTS '
                'could be imported'
            ) from exc
        formats = IMAGE_EXTS
    return tuple(sorted('.' + str(fmt).lower().lstrip('.') for fmt in formats))


def _count_images(dataset_dir, split_dirname):
    """Number of image files in {dataset_dir}/{split_dirname}/images; 0 when the folder is absent.

    Every type the trainer reads counts (_image_suffixes), so the ledger row
    and the report's split sizes state the whole split and not the part of it
    written in the commonest formats. Anything else in the folder (label text, a checksum file) is
    ignored, and so is anything that is not a readable file: a subfolder whose
    name ends in an image suffix, or a symlink with nothing behind it, is not
    an image the scorer can open.

    Parameters:
        dataset_dir (str): the split dataset folder.
        split_dirname (str): 'train', 'valid' or 'test'.

    Returns:
        int: the count, 0 when the images folder is missing or unreadable.

    Callers:
        the rounds ledger's n_train, n_valid and n_test columns, and
        gather_context, which puts the same counts in report.md, on the PDF
        cover and in metrics.json.
    """
    p = os.path.join(dataset_dir, split_dirname, 'images')
    if not os.path.isdir(p):
        return 0
    suffixes = _image_suffixes()
    try:
        with os.scandir(p) as entries:
            return sum(1 for e in entries
                       if e.name.lower().endswith(suffixes) and e.is_file())
    except OSError as exc:
        print(f'[eval] cannot list {p}, image count recorded as 0: {exc}')
        return 0


def _split_pinned(dataset_dir):
    """True when the dataset's split is frozen and reproducible.

    split_manifest.json qualifies when it records a by-transect holdout
    (holdout_mode 'transect') or a per-image pin table under 'pins' (the
    detection stager) or 'pinned' (the segmentation splitter), whichever
    splitter wrote it. No manifest, or a manifest with neither, is a loose
    split and every gate reads unpinned.

    Parameters:
        dataset_dir: the split dataset folder.
    Returns:
        bool.
    Raises:
        ValueError when the manifest exists but is not a JSON object.
    """
    manifest_path = os.path.join(dataset_dir, SPLIT_MANIFEST_NAME)
    if not os.path.isfile(manifest_path):
        return False
    try:
        with open(manifest_path) as f:
            manifest = json.load(f)
    except json.JSONDecodeError as exc:
        raise ValueError(f'split manifest {manifest_path} is not valid JSON: {exc}') from exc
    if not isinstance(manifest, dict):
        raise ValueError(
            f'split manifest {manifest_path} must hold a JSON object, got {type(manifest).__name__}'
        )
    if manifest.get('holdout_mode') == HOLDOUT_MODE_TRANSECT:
        return True
    return any(isinstance(manifest.get(k), dict) and manifest.get(k) for k in MANIFEST_PIN_KEYS)


def _classes_trained(dataset_dir):
    """Set of class NAMES that have at least one labeled instance in the
    train split. Used so gate_class ignores classes never trained on (a
    never-trained class reporting ~0 AP must not trip the regression gate)."""
    data_yaml_path = os.path.join(dataset_dir, 'data.yaml')
    names = {}
    if os.path.isfile(data_yaml_path):
        try:
            with open(data_yaml_path) as f:
                data = yaml.safe_load(f) or {}
            raw_names = data.get('names') or {}
            if isinstance(raw_names, dict):
                names = {int(k): v for k, v in raw_names.items() if v is not None}
            elif isinstance(raw_names, list):
                names = {i: v for i, v in enumerate(raw_names) if v is not None}
        except (OSError, yaml.YAMLError, ValueError) as exc:
            raise ValueError(f'{data_yaml_path} cannot be read for the class names: {exc}') from exc

    train_lbl_dir = os.path.join(dataset_dir, 'train', 'labels')
    present_ids = set()
    if os.path.isdir(train_lbl_dir):
        for fn in os.listdir(train_lbl_dir):
            if not fn.lower().endswith('.txt'):
                continue
            label_path = os.path.join(train_lbl_dir, fn)
            try:
                with open(label_path, encoding='utf-8', errors='replace') as f:
                    for line in f:
                        parts = line.split()
                        if not parts:
                            continue
                        try:
                            present_ids.add(int(parts[0]))
                        except ValueError:
                            continue  # not a label line; the preview parser reports these per line
            except OSError as exc:
                print(f'[eval] {label_path} unreadable, its classes are not counted as trained: {exc}')

    if names:
        return {nm for cid, nm in names.items() if cid in present_ids}
    # No data.yaml names available: fall back to whatever class ids we saw,
    # stringified, so the caller still has something to compare against.
    return {str(cid) for cid in present_ids}


def _load_champion(rounds_dir):
    """The champion.json dict for a ledger folder, or None when no champion is recorded.

    Raises:
        ValueError when the file exists but is not a JSON object, because a
        corrupt champion silently changing the gate baseline is a false verdict.
    """
    champion_path = os.path.join(rounds_dir, 'champion.json')
    if not os.path.isfile(champion_path):
        return None
    try:
        with open(champion_path) as f:
            champion = json.load(f)
    except json.JSONDecodeError as exc:
        raise ValueError(f'champion file {champion_path} is not valid JSON: {exc}') from exc
    if not isinstance(champion, dict):
        raise ValueError(f'champion file {champion_path} must hold a JSON object, got {type(champion).__name__}')
    return champion


def _ledger_column(family, suffix):
    """rounds.csv column for one family score, e.g. ('box', 'map50_95') -> 'map50_95_B'.

    Parameters:
        family: METRIC_FAMILY_MASK or METRIC_FAMILY_BOX.
        suffix: one of METRIC_SUFFIXES.
    Returns:
        The column name.
    """
    if suffix not in METRIC_SUFFIXES:
        raise ValueError(f'unknown metric suffix {suffix!r}; expected one of {METRIC_SUFFIXES}')
    return f'{suffix}_{FAMILY_LEDGER_SUFFIX[family]}'


def _cell_float(row, column):
    """Float value of one ledger cell.

    Parameters:
        row: a rounds.csv row dict (or a synthetic baseline row).
        column: the column name.
    Returns:
        float, or None when the cell is blank or the column is absent.
    Raises:
        ValueError when the cell holds something that is not a number.
    """
    raw = row.get(column)
    if raw is None:
        return None
    if isinstance(raw, (int, float)):
        return float(raw)
    text = str(raw).strip()
    if not text:
        return None
    try:
        return float(text)
    except ValueError as exc:
        raise ValueError(f'rounds.csv cell {column}={raw!r} is not a number') from exc


def _row_family(row):
    """Metric family of one ledger row.

    The metric_family column decides when present; rows written before the
    column existed are classified by which mAP50-95 column holds a number.

    Parameters:
        row: a rounds.csv row dict.
    Returns:
        METRIC_FAMILY_MASK, METRIC_FAMILY_BOX, or None for a row with no numbers.
    """
    explicit = str(row.get('metric_family') or '').strip()
    if explicit in METRIC_FAMILIES:
        return explicit
    for family in METRIC_FAMILIES:
        if _cell_float(row, _ledger_column(family, 'map50_95')) is not None:
            return family
    return None


BASELINE_FOUND = 'found'
BASELINE_NONE = 'none'
BASELINE_OTHER_FAMILY = 'other family'
# The baseline scores the same family but was not measured the same way: it
# records another confidence cut-off, or it records none while this round
# does. mAP is the area under the whole precision-recall curve, so the same
# weights score lower at a higher cut-off and the two numbers are not a
# comparison. Only the confidence is treated this way: the image size follows
# each run's own training size by design, so treating a change there as
# incomparable would silence the gates on almost every ledger.
BASELINE_OTHER_SETTINGS = 'other settings'
# Two recorded confidences count as the same measurement within this much,
# which absorbs a CSV round trip and nothing else.
CONF_MATCH_TOLERANCE = 1e-9


def _select_baseline_row(rows, champion, family):
    """Baseline for gate comparisons: the CURRENT champion's row if one
    exists (matched by run_dir, falling back to run_name), else the row
    with the highest mAP50-95 of the same family among existing rows.
    NEVER the last-appended row by position.

    Parameters:
        rows: prior ledger rows, excluding this run's own row.
        champion: the champion.json dict, or None.
        family: this round's metric family.
    Returns:
        (row, status): status is BASELINE_FOUND with a same-family row,
        BASELINE_OTHER_FAMILY when the only candidate scores a different
        family (row may be None), or BASELINE_NONE when no prior round exists.
    """
    if champion:
        champ_run_dir = champion.get('run_dir')
        champ_run_name = _run_name_of(champ_run_dir) if champ_run_dir else None
        for row in rows:
            if (champ_run_dir and row.get('run_dir') == champ_run_dir) or \
               (champ_run_name and row.get('run_name') == champ_run_name):
                status = BASELINE_FOUND if _row_family(row) == family else BASELINE_OTHER_FAMILY
                return row, status
        # Champion recorded but no matching row yet (e.g. champion.json
        # fixture points at a run not present in rounds.csv): fall back to
        # its own recorded map50_95_M as a synthetic mask-family baseline.
        if champion.get('map50_95_M') is not None:
            synthetic = {'map50_95_M': champion['map50_95_M'], 'recall_M': None,
                         'per_class_json': None, 'metric_family': METRIC_FAMILY_MASK}
            status = BASELINE_FOUND if family == METRIC_FAMILY_MASK else BASELINE_OTHER_FAMILY
            return synthetic, status

    map_column = _ledger_column(family, 'map50_95')
    best = None
    best_val = None
    for row in rows:
        if _row_family(row) != family:
            continue
        v = _cell_float(row, map_column)
        if v is not None and (best_val is None or v > best_val):
            best_val = v
            best = row
    if best is not None:
        return best, BASELINE_FOUND
    if any(_row_family(r) not in (None, family) for r in rows):
        return None, BASELINE_OTHER_FAMILY
    return None, BASELINE_NONE


def _recorded_conf(row):
    """The confidence one ledger row records, or None when it records none.

    A hand-edited rounds.csv can hold anything in that cell; anything that is
    not a number reads as "not recorded", because an evaluation must never
    fail over a cell somebody typed into.

    Parameters:
        row: a rounds.csv row dict, a synthetic baseline row, or None.
    Returns:
        The confidence as a float, or None.

    Example:
        _recorded_conf({'conf': '0.001'}) -> 0.001
    """
    if not row:
        return None
    raw = row.get('conf')
    if raw is None or (isinstance(raw, str) and not raw.strip()):
        return None
    try:
        return float(raw)
    except (TypeError, ValueError):
        return None


def _same_measurement(baseline_row, conf):
    """Whether a baseline's score may be ranked against a round measured at conf.

    Parameters:
        baseline_row: the ledger row the gates would compare against.
        conf: what this round was measured with: a float, or '' when the
            caller recorded nothing.
    Returns:
        True when both rows record the same confidence, and True when NEITHER
        records one, which is how the ledger behaved before the columns
        existed. False when only one of the two records a confidence, or when
        the two differ.

    Example:
        _same_measurement({'conf': '0.25'}, 0.001) -> False
    """
    baseline_conf = _recorded_conf(baseline_row)
    round_conf = _recorded_conf({'conf': conf})
    if baseline_conf is None and round_conf is None:
        return True
    if baseline_conf is None or round_conf is None:
        return False
    return abs(baseline_conf - round_conf) <= CONF_MATCH_TOLERANCE


def _prev_per_class(rounds_dir, baseline_row, family):
    """Load the baseline row's per-class mAP50-95 vector for one family
    (class name -> AP) from its sidecar JSON.

    Parameters:
        rounds_dir: the ledger folder.
        baseline_row: the row whose per_class_json sidecar to read, or None.
        family: the metric family to read.
    Returns:
        dict class name -> float; {} when the row has no sidecar on disk.
    Raises:
        ValueError when the sidecar exists but is not valid JSON.
    """
    if not baseline_row:
        return {}
    rel = baseline_row.get('per_class_json')
    if not rel:
        return {}
    path = rel if os.path.isabs(rel) else os.path.join(rounds_dir, rel)
    if not os.path.isfile(path):
        return {}
    try:
        with open(path) as f:
            data = json.load(f)
    except json.JSONDecodeError as exc:
        raise ValueError(f'per-class sidecar {path} is not valid JSON: {exc}') from exc
    key = family_key(family, 'map50_95')
    return {k: v.get(key) for k, v in data.items()
            if isinstance(v, dict) and v.get(key) is not None}


def _class_code(name):
    """Short gate-report code for a class name: first letters of each
    whitespace, underscore or dash separated token, uppercased (e.g.
    'Porites astreoides' or 'Porites-astreoides' -> 'PA'). Falls back to
    the first two characters.

    Parameters:
        name: the class token.
    Returns:
        The code string.
    """
    tokens = [t for t in re.split(r'[ _-]+', name) if t]
    if len(tokens) >= 2:
        return ''.join(t[0] for t in tokens[:4]).upper()
    return name[:2].upper() if name else '??'


def _gate_verdicts(baseline_row, family, overall, per_class, rounds_dir, dataset_dir):
    """The three gate verdicts of this round against a same-family baseline row.

    Parameters:
        baseline_row: the ledger row (or synthetic row) to compare against.
        family: the metric family both rows score.
        overall: this round's metrics['overall'].
        per_class: this round's metrics['per_class'].
        rounds_dir: the ledger folder, for the baseline's per-class sidecar.
        dataset_dir: the split dataset, for the set of trained classes.
    Returns:
        (gate_map, gate_class, gate_recall) verdict strings.
    """
    cur_map = overall.get(family_key(family, 'map50_95'))
    cur_recall = overall.get(family_key(family, 'recall'))
    prev_map = _cell_float(baseline_row, _ledger_column(family, 'map50_95'))
    prev_recall = _cell_float(baseline_row, _ledger_column(family, 'recall'))

    if prev_map is None or cur_map is None:
        gate_map = GATE_PASS
    else:
        gate_map = GATE_PASS if cur_map >= prev_map - GATE_MAP_EPS else GATE_FAIL

    if prev_recall is None or cur_recall is None:
        gate_recall = GATE_PASS
    else:
        gate_recall = GATE_PASS if cur_recall >= prev_recall - GATE_RECALL_DROP else GATE_FLAG

    trained_classes = _classes_trained(dataset_dir)
    prev_per_class = _prev_per_class(rounds_dir, baseline_row, family)
    ap_key = family_key(family, 'map50_95')
    dropped_codes = []
    for cls_name, cur_d in per_class.items():
        if trained_classes and cls_name not in trained_classes:
            continue  # never-trained class: ignore per FIX 9 / Task 7 rule 5b
        cur_ap = cur_d.get(ap_key) if isinstance(cur_d, dict) else None
        prev_ap = prev_per_class.get(cls_name)
        if cur_ap is None or prev_ap is None:
            continue
        if prev_ap - cur_ap > GATE_CLASS_DROP:
            dropped_codes.append(_class_code(cls_name))
    gate_class = GATE_PASS if not dropped_codes else GATE_FLAG + ':' + ','.join(sorted(dropped_codes))
    return gate_map, gate_class, gate_recall


def _eval_settings(conf, iou, imgsz):
    """The measurement settings one ledger row records, validated.

    A score only means something beside the settings it was measured with:
    mAP is the area under the whole precision-recall curve, so raising the
    confidence cut-off reports a lower number for the very same weights.

    Parameters:
        conf: the confidence cut-off the evaluation ran at, or None when the
            caller does not know it (a caller written before 2026-09-15).
        iou: the non-maximum-suppression overlap, or None.
        imgsz: the square image size in pixels, or None.
    Returns:
        A dict keyed by ROUNDS_SETTINGS_COLUMNS, each value a number, or the
        empty string when the caller supplied none.
    Raises:
        ValueError naming the setting and the value when it is not a number.

    Example:
        _eval_settings(0.001, 0.6, 512) -> {'conf': 0.001, 'iou': 0.6, 'imgsz': 512}
    """
    casts = (('conf', conf, float), ('iou', iou, float), ('imgsz', imgsz, int))
    settings = {}
    for name, value, cast in casts:
        if value is None or value == '':
            settings[name] = ''
            continue
        try:
            settings[name] = cast(value)
        except (TypeError, ValueError) as exc:
            raise ValueError(
                f'the rounds ledger cannot record {name}={value!r}: it is not a number'
            ) from exc
    return settings


def _ledger_row(round_num, run_name, run_dir, dataset_dir, overall, family, pinned, gates,
                per_class_rel, settings):
    """Assemble one rounds.csv row dict in ROUNDS_CSV_HEADER order.

    Parameters:
        round_num: 1-based round number.
        run_name, run_dir: the evaluated run.
        dataset_dir: the split dataset, for image counts.
        overall: metrics['overall'].
        family: the metric family the gates were computed on.
        pinned: whether the split is frozen.
        gates: (gate_map, gate_class, gate_recall).
        per_class_rel: sidecar path relative to the ledger folder.
        settings: _eval_settings() output, what the score was measured with.
    Returns:
        The row dict.
    """
    gate_map, gate_class, gate_recall = gates
    row = {
        'round': round_num,
        'at': ast_now(),
        'run_name': run_name,
        'run_dir': run_dir,
        'base_model': _base_model_of(run_dir),
        'split_pinned': 'true' if pinned else 'false',
        'n_train': _count_images(dataset_dir, 'train'),
        'n_valid': _count_images(dataset_dir, 'valid'),
        'n_test': _count_images(dataset_dir, 'test'),
        'gate_map': gate_map,
        'gate_class': gate_class,
        'gate_recall': gate_recall,
        'per_class_json': per_class_rel,
        'metric_family': family,
        'metrics_schema': ROUNDS_METRICS_SCHEMA,
        **settings,
    }
    for fam in METRIC_FAMILIES:
        for suffix in METRIC_SUFFIXES:
            row[_ledger_column(fam, suffix)] = overall.get(family_key(fam, suffix))
    return row


def append_round_row(rounds_dir, run_dir, metrics_dict, dataset_dir,
                     *, conf=None, iou=None, imgsz=None):
    """Write/update one row of {rounds_dir}/rounds.csv for this run's eval.

    Pure function: no ultralytics import, no network/model access. Idempotent
    and lineage-aware:
      - keyed by run_name (basename of run_dir): re-evaluating an existing
        run UPDATES its row in place, never appends a duplicate.
      - gate baseline is the CURRENT champion (champion.json) if present,
        else the highest-mAP prior round of the same metric family; never
        the last-appended row.
      - gates are computed on the family this run produced (mask for a
        segmentation run, box for a detector). A baseline of the other
        family, or one measured at another confidence cut-off, yields
        GATE_INCOMPARABLE on all three gates; a loose split yields
        GATE_UNPINNED.

    Parameters:
        rounds_dir: the ledger folder.
        run_dir: the evaluated run folder.
        metrics_dict: extract_metrics() output (or a dict shaped like it).
        dataset_dir: the split dataset folder.
        conf, iou, imgsz: what this score was measured with, recorded in the
            row so two rows can be ranked. Left out (the default) writes those
            three cells empty rather than guessing a number.
    Returns:
        The row dict that was written.
    Raises:
        ValueError naming the setting when conf, iou or imgsz is not a number.
    """
    settings = _eval_settings(conf, iou, imgsz)
    os.makedirs(rounds_dir, exist_ok=True)
    rounds_csv_path = os.path.join(rounds_dir, 'rounds.csv')
    rows = _read_rounds_csv(rounds_csv_path)

    run_name = _run_name_of(run_dir)
    family = metric_family(metrics_dict)

    existing_idx = None
    for i, row in enumerate(rows):
        if row.get('run_name') == run_name or row.get('run_dir') == run_dir:
            existing_idx = i
            break

    # Baseline is selected from rows EXCLUDING this run's own prior row (if
    # any), so a re-eval of the same run never baselines against itself.
    other_rows = [r for i, r in enumerate(rows) if i != existing_idx]
    champion = _load_champion(rounds_dir)
    baseline_row, status = _select_baseline_row(other_rows, champion, family)
    # A same-family baseline measured with another confidence is not a
    # baseline: the coral ledger's rows were measured at 0.25 and a round
    # measured at 0.001 reads about 0.06 mAP50 higher on the same weights, so
    # ranking them would credit the change of threshold to the model.
    if status == BASELINE_FOUND and not _same_measurement(baseline_row, settings['conf']):
        status = BASELINE_OTHER_SETTINGS

    overall = metrics_dict.get('overall', {})
    per_class = metrics_dict.get('per_class', {})
    pinned = _split_pinned(dataset_dir)

    round_num = existing_idx + 1 if existing_idx is not None else len(rows) + 1
    per_class_rel = f'rounds/round_{round_num}_per_class.json'
    per_class_abs = os.path.join(rounds_dir, per_class_rel)
    os.makedirs(os.path.dirname(per_class_abs), exist_ok=True)
    with open(per_class_abs, 'w') as f:
        json.dump(per_class, f, indent=2, default=str)

    if not pinned:
        gates = (GATE_UNPINNED, GATE_UNPINNED, GATE_UNPINNED)
    elif status in (BASELINE_OTHER_FAMILY, BASELINE_OTHER_SETTINGS):
        gates = (GATE_INCOMPARABLE, GATE_INCOMPARABLE, GATE_INCOMPARABLE)
    elif status == BASELINE_NONE:
        gates = (GATE_PASS, GATE_PASS, GATE_PASS)
    else:
        gates = _gate_verdicts(baseline_row, family, overall, per_class, rounds_dir, dataset_dir)

    row = _ledger_row(round_num, run_name, run_dir, dataset_dir, overall, family, pinned,
                      gates, per_class_rel, settings)
    if existing_idx is not None:
        rows[existing_idx] = row
    else:
        rows.append(row)

    _write_rounds_csv(rounds_csv_path, rows)
    return row


