def _find_best_weights(run_dir):
    """Path to weights/best.pt, else weights/last.pt, under run_dir; FileNotFoundError when neither exists."""
    cand = [os.path.join(run_dir, 'weights', 'best.pt'),
            os.path.join(run_dir, 'weights', 'last.pt')]
    for c in cand:
        if os.path.isfile(c):
            return c
    raise FileNotFoundError(f'No weights/best.pt or weights/last.pt in {run_dir}')


def _resolve_data_yaml(dataset_dir, split):
    """Path to data.yaml inside dataset_dir; FileNotFoundError when it is absent."""
    cand = [os.path.join(dataset_dir, 'data.yaml')]
    for c in cand:
        if os.path.isfile(c):
            return c
    raise FileNotFoundError(f'No data.yaml in {dataset_dir}')


def run_val(args):
    """Run ultralytics validation on the run's best weights; return the results object with timing and paths."""
    from ultralytics import YOLO
    weights = _find_best_weights(args.run_dir)
    data_yaml = _resolve_data_yaml(args.dataset_dir, args.split)
    model = YOLO(weights)

    out_dir = args.out_dir
    os.makedirs(out_dir, exist_ok=True)
    val_dir = os.path.join(out_dir, 'val_run')
    os.makedirs(val_dir, exist_ok=True)

    batch = args.batch if args.batch and args.batch > 0 else 8

    t0 = time.time()
    results = model.val(
        data=data_yaml,
        split=args.split,
        imgsz=args.imgsz,
        batch=batch,
        conf=args.conf,
        iou=args.iou,
        device=args.device,
        project=out_dir,
        name='val_run',
        exist_ok=True,
        plots=True,
        save_json=True,
        save_txt=False,
        save_conf=True,
    )
    wall = time.time() - t0

    return {
        'weights': weights,
        'data_yaml': data_yaml,
        'wall_seconds': wall,
        'results': results,
        'val_dir': val_dir,
        'model': model,
    }


