def _plan_pages(n_per_class_rows, n_previews):
    """Page number of every section of the report, from the two counts that vary.

    Parameters:
        n_per_class_rows: scored plus absent classes (rows of the per-class table).
        n_previews: prediction sample images.
    Returns:
        dict with the first page of 'cover', 'training', 'box', 'mask',
        'per_class', 'per_class_table', 'confusion', 'samples' (None when
        there are no previews) and 'glossary'; 'n_table_pages',
        'n_sample_pages' and 'total'; and 'toc', the (label, page) list the
        cover prints.
    Raises:
        TypeError or ValueError when a count is not a non-negative integer.
    """
    for name, value in (('n_per_class_rows', n_per_class_rows), ('n_previews', n_previews)):
        if isinstance(value, bool) or not isinstance(value, int):
            raise TypeError(f'{name} must be an integer, got {type(value).__name__}')
        if value < 0:
            raise ValueError(f'{name} must not be negative, got {value}')
    n_table_pages = max(1, -(-n_per_class_rows // PER_CLASS_ROWS_PER_PAGE))
    n_sample_pages = -(-n_previews // SAMPLES_PER_PAGE)
    plan = {'cover': 1, 'training': 2, 'box': 3, 'mask': 4, 'per_class': 5, 'per_class_table': 6,
            'n_table_pages': n_table_pages, 'n_sample_pages': n_sample_pages}
    plan['confusion'] = plan['per_class_table'] + n_table_pages
    plan['samples'] = plan['confusion'] + 1 if n_sample_pages else None
    plan['glossary'] = plan['confusion'] + 1 + n_sample_pages
    plan['total'] = plan['glossary']
    toc = [
        ('Cover + top-line', plan['cover']),
        ('Training history', plan['training']),
        ('Box metrics', plan['box']),
        ('Mask metrics', plan['mask']),
        ('Per-class breakdown', plan['per_class']),
        (f'Per-class table ({n_per_class_rows} classes)', plan['per_class_table']),
        ('Confusion matrix', plan['confusion']),
    ]
    if n_sample_pages:
        toc.append((f'Prediction samples ({n_previews} imgs)', plan['samples']))
    toc.append(('Glossary cheatsheet', plan['glossary']))
    plan['toc'] = toc
    return plan


def _assemble_report_html(title, css, sections):
    """The complete report document with the stylesheet inlined in <head>.

    Chrome's print path takes no stylesheet argument, so the CSS travels
    inside the document, which is then self-contained apart from its images.

    Parameters:
        title: document title (escaped here).
        css: the stylesheet text from _build_css().
        sections: HTML strings, one <section class="page"> each, in page order.
    Returns:
        The HTML document string, with any subject placeholder still in it
        filled, so prose added to a page later cannot reach a reader as
        "{subject}".
    Raises:
        ValueError when css is blank or sections is empty.
    """
    if not css or not css.strip():
        raise ValueError('report stylesheet is empty')
    if not sections:
        raise ValueError('report has no sections to print')
    return fill_subject(
        '<!DOCTYPE html><html><head><meta charset="utf-8">'
        f'<title>{_html_escape(title)}</title>'
        f'<style>{css}</style>'
        '</head><body>'
        + ''.join(sections)
        + '</body></html>'
    )


def _write_report_html(out_dir, html_str):
    """Write the report document to out_dir/REPORT_HTML_NAME and return its path.

    Parameters:
        out_dir: the evaluation output folder (must exist).
        html_str: the document from _assemble_report_html.
    Returns:
        Absolute path of the written file.
    Raises:
        NotADirectoryError when out_dir is not a folder; OSError naming the
        path when the write fails.
    """
    if not os.path.isdir(out_dir):
        raise NotADirectoryError(f'cannot write {REPORT_HTML_NAME}: {out_dir} is not a folder')
    path = os.path.join(os.path.abspath(out_dir), REPORT_HTML_NAME)
    try:
        with open(path, 'w', encoding='utf-8') as fh:
            fh.write(html_str)
    except OSError as exc:
        raise OSError(f'writing {path} failed: {exc}') from exc
    return path


def _chrome_binary():
    """Path of the Chrome binary: CHROME_BINARY_ENV when set, else CHROME_BINARY_DEFAULT.

    Returns:
        The path string.
    Raises:
        FileNotFoundError when the path is not an executable file.
    """
    path = os.environ.get(CHROME_BINARY_ENV) or CHROME_BINARY_DEFAULT
    if not os.path.isfile(path) or not os.access(path, os.X_OK):
        raise FileNotFoundError(
            f'Chrome binary {path} is not an executable file; install Google Chrome there '
            f'or point {CHROME_BINARY_ENV} at it'
        )
    return path


def _stderr_tail(text):
    """The last CHROME_STDERR_TAIL_LINES lines of a captured stderr, as one string.

    Parameters:
        text: str, bytes or None (a timeout leaves bytes or nothing).
    Returns:
        The tail, or '(no stderr)' when there was none.
    """
    if isinstance(text, bytes):
        text = text.decode('utf-8', errors='replace')
    lines = [ln for ln in (text or '').splitlines() if ln.strip()]
    if not lines:
        return '(no stderr)'
    return ' | '.join(lines[-CHROME_STDERR_TAIL_LINES:])


def _discard_bad_pdf(pdf_path):
    """Remove a file Chrome left that is not a valid PDF, so no reader mistakes it for a report.

    Parameters:
        pdf_path: the file to remove; nothing happens when it does not exist.
    """
    if not os.path.exists(pdf_path):
        return
    try:
        os.remove(pdf_path)
    except OSError as exc:
        print(f'[eval] could not remove the invalid PDF at {pdf_path}: {exc}')


def _verify_pdf_file(pdf_path, chrome_stderr):
    """Prove that pdf_path is a PDF: it exists, it is not empty, it starts with PDF_MAGIC_BYTES.

    Parameters:
        pdf_path: the file Chrome was asked to write.
        chrome_stderr: Chrome's captured stderr, quoted in the error.
    Raises:
        RuntimeError naming the path and the reason, after removing a file
        that is not a PDF.
    """
    tail = _stderr_tail(chrome_stderr)
    if not os.path.isfile(pdf_path):
        raise RuntimeError(f'Chrome exited 0 but wrote no PDF at {pdf_path}; stderr tail: {tail}')
    if os.path.getsize(pdf_path) == 0:
        _discard_bad_pdf(pdf_path)
        raise RuntimeError(f'Chrome left an empty file at {pdf_path}; stderr tail: {tail}')
    with open(pdf_path, 'rb') as fh:
        head = fh.read(len(PDF_MAGIC_BYTES))
    if head != PDF_MAGIC_BYTES:
        _discard_bad_pdf(pdf_path)
        raise RuntimeError(
            f'{pdf_path} does not start with {PDF_MAGIC_BYTES!r} (got {head!r}), so it is not '
            f'a PDF; stderr tail: {tail}'
        )


def _pdf_page_count(pdf_path):
    """Page count of a PDF via PDFINFO_BINARY.

    Parameters:
        pdf_path: a verified PDF.
    Returns:
        The count, or None when pdfinfo is not installed or could not read
        the file (the reason is printed).
    """
    if not os.path.isfile(PDFINFO_BINARY):
        return None
    try:
        proc = subprocess.run([PDFINFO_BINARY, pdf_path], capture_output=True, text=True,
                              timeout=PDFINFO_TIMEOUT_SECONDS)
    except (OSError, subprocess.TimeoutExpired) as exc:
        print(f'[eval] pdfinfo could not count the pages of {pdf_path}: {exc}')
        return None
    if proc.returncode != 0:
        print(f'[eval] pdfinfo exited {proc.returncode} on {pdf_path}: {_stderr_tail(proc.stderr)}')
        return None
    for line in proc.stdout.splitlines():
        if line.startswith('Pages:'):
            value = line.split(':', 1)[1].strip()
            try:
                return int(value)
            except ValueError:
                print(f'[eval] pdfinfo reported a page count that is not a number for {pdf_path}: {value!r}')
                return None
    print(f'[eval] pdfinfo printed no page count for {pdf_path}')
    return None


def print_html_to_pdf_with_chrome(html_path, pdf_path, timeout_seconds=CHROME_PRINT_TIMEOUT_SECONDS):
    """Print a local HTML file to PDF with headless Chrome and prove the result.

    Chrome exits 0 whether or not it printed anything, so after it returns
    the PDF is checked for existence, a non-zero size and the %PDF- magic
    bytes; anything else raises with the tail of Chrome's stderr. Each call
    runs in its own process group on its own throwaway profile folder, which
    is removed in every case, timeout included.

    Parameters:
        html_path: the report document (images resolve against its folder).
        pdf_path: where the PDF goes; its folder must exist.
        timeout_seconds: how long Chrome may run before its process group is killed.
    Returns:
        The page count from pdfinfo, or None when pdfinfo is not installed.
    Raises:
        FileNotFoundError when the HTML, the output folder or the browser is missing.
        ValueError when timeout_seconds is not positive.
        RuntimeError when Chrome times out, exits non-zero or leaves no valid PDF.
    """
    if not os.path.isfile(html_path):
        raise FileNotFoundError(f'cannot print {html_path}: no such file')
    pdf_abs = os.path.abspath(pdf_path)
    out_dir = os.path.dirname(pdf_abs)
    if not os.path.isdir(out_dir):
        raise FileNotFoundError(f'cannot write {pdf_path}: folder {out_dir} does not exist')
    if isinstance(timeout_seconds, bool) or not isinstance(timeout_seconds, (int, float)) or timeout_seconds <= 0:
        raise ValueError(f'timeout_seconds must be a positive number, got {timeout_seconds!r}')
    binary = _chrome_binary()
    profile_dir = tempfile.mkdtemp(prefix=CHROME_PROFILE_PREFIX)
    cmd = [binary, *CHROME_PRINT_FLAGS, f'--user-data-dir={profile_dir}',
           f'--print-to-pdf={pdf_abs}', _file_uri(html_path)]
    try:
        proc = subprocess.Popen(cmd, stdout=subprocess.PIPE, stderr=subprocess.PIPE,
                                text=True, start_new_session=True)
        try:
            _stdout, stderr = proc.communicate(timeout=timeout_seconds)
        except subprocess.TimeoutExpired as exc:
            os.killpg(proc.pid, signal.SIGKILL)
            _stdout, stderr = proc.communicate()
            _discard_bad_pdf(pdf_abs)
            raise RuntimeError(
                f'Chrome timed out after {timeout_seconds} s printing {html_path} to {pdf_path}; '
                f'stderr tail: {_stderr_tail(stderr)}'
            ) from exc
    finally:
        try:
            shutil.rmtree(profile_dir)
        except OSError as exc:
            print(f'[eval] could not remove the throwaway Chrome profile {profile_dir}: {exc}')
    if proc.returncode != 0:
        _discard_bad_pdf(pdf_abs)
        raise RuntimeError(
            f'Chrome exited {proc.returncode} printing {html_path} to {pdf_path}; '
            f'stderr tail: {_stderr_tail(stderr)}'
        )
    _verify_pdf_file(pdf_abs, stderr)
    return _pdf_page_count(pdf_abs)


def build_pdf(metrics, ctx, previews, args, pdf_path):
    """Assemble the report HTML, write it beside the PDF and print it with Chrome.

    Every page number comes from _plan_pages, so the page titles, the footer
    and the table of contents on the cover agree (layout in the module
    docstring). report.html is written before Chrome runs and stays on disk.

    Parameters:
        metrics: extract_metrics() output.
        ctx: gather_context() output.
        previews: render_previews() output.
        args: parsed CLI arguments (out_dir, split, conf, iou, imgsz).
        pdf_path: where the PDF goes.
    Returns:
        The page count from pdfinfo, or None when pdfinfo is not installed.
    Raises:
        ValueError when metrics carries no class names or the rendered
        sections disagree with the plan; OSError when report.html cannot be
        written; RuntimeError when Chrome produces no valid PDF.
    """
    if not isinstance(metrics, dict) or not metrics.get('class_names'):
        raise ValueError('build_pdf needs a metrics dict with class_names')
    out_dir = args.out_dir
    os.makedirs(out_dir, exist_ok=True)
    run_name = os.path.basename(ctx['run_dir'].rstrip('/'))
    now = ast_report_stamp()

    figures = _collect_figures(ctx, args, out_dir)
    figures['per_class_bar'] = _per_class_bar_figure(metrics, out_dir)
    n_rows = len(metrics.get('per_class') or {}) + len(metrics.get('absent_classes') or [])
    plan = _plan_pages(n_rows, len(previews))

    sections = [
        _render_cover(metrics, ctx, args, plan['toc'], now, run_name),
        _render_training(metrics, ctx, args, figures, plan['training']),
        _render_metric_page('box', plan['box'], metrics, ctx, args, figures),
        _render_metric_page('mask', plan['mask'], metrics, ctx, args, figures),
    ]
    sections.extend(_render_perclass(metrics, args, figures, plan))
    sections.append(_render_confusion(metrics, ctx, args, figures, plan['confusion']))
    sample_pages, next_page = _render_samples(previews, args, plan['confusion'] + 1,
                                             metric_family(metrics))
    if next_page != plan['glossary']:
        raise ValueError(
            f'sample pages end at page {next_page} but the plan puts the glossary on '
            f'page {plan["glossary"]}'
        )
    sections.extend(sample_pages)
    sections.append(_render_glossary(metrics, ctx, args, plan['glossary'], now))
    if len(sections) != plan['total']:
        raise ValueError(f'{len(sections)} sections rendered but the plan counts {plan["total"]} pages')

    html_str = _assemble_report_html(f'Evaluation report: {run_name}', _build_css(), sections)
    html_path = _write_report_html(out_dir, html_str)
    n_pages = print_html_to_pdf_with_chrome(html_path, pdf_path)
    if n_pages is not None and n_pages != plan['total']:
        print(f'[eval] WARNING: the PDF has {n_pages} pages but the page plan counts {plan["total"]}; '
              'a section overflowed its sheet, so the page numbers printed after it are off by '
              'the difference')
    pages_note = f' ({n_pages} pages)' if n_pages is not None else ''
    print(f'[eval] PDF written via Chrome: {pdf_path}{pages_note}')
    return n_pages


