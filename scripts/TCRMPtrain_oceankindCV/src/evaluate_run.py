def _md_top_line_table(overall, family):
    """Markdown lines for the top-line table: box and mask columns for a
    segmentation run, a box column alone for a detector.

    Parameters:
        overall: metrics['overall'].
        family: the run's metric family.
    Returns:
        list of markdown table lines.
    """
    rows = (('mAP50', 'map50', GOOD_RANGES['mAP50']),
            ('mAP50-95', 'map50_95', GOOD_RANGES['mAP50-95']),
            ('Precision', 'precision', GOOD_RANGES['P/R']),
            ('Recall', 'recall', GOOD_RANGES['P/R']))
    lines = []
    if family == METRIC_FAMILY_MASK:
        lines.append('| Metric | Box | Mask | Good range |')
        lines.append('|---|---|---|---|')
        for label, suffix, good in rows:
            lines.append(f'| {label} | {fmt_num(overall.get(family_key(METRIC_FAMILY_BOX, suffix)))} | '
                         f'{fmt_num(overall.get(family_key(METRIC_FAMILY_MASK, suffix)))} | {good} |')
        return lines
    lines.append('| Metric | Box | Good range |')
    lines.append('|---|---|---|')
    for label, suffix, good in rows:
        lines.append(f'| {label} | {fmt_num(overall.get(family_key(METRIC_FAMILY_BOX, suffix)))} | {good} |')
    return lines


def _md_per_class_section(metrics, family, split):
    """Markdown lines for the per-class table of one family, every class
    named, absent classes marked rather than left blank.

    Parameters:
        metrics: extract_metrics() output.
        family: the run's metric family.
        split: the evaluated split name, for the prose.
    Returns:
        list of markdown lines, empty when the run has no classes at all.
    """
    pc = metrics.get('per_class') or {}
    inst = metrics.get('per_class_instances') or {}
    absent = set(metrics.get('absent_classes') or [])
    names = set((metrics.get('class_names') or {}).values()) | set(pc) | absent
    if not names:
        return []
    label = FAMILY_LABELS[family]
    _subject_singular, subject_plural = subject_nouns()
    source = metrics.get('per_class_instances_source')
    source_note = f' (source: {source})' if source else ''
    lines = [f'## Per-class ({label} scores)', '']
    lines.append(
        f"Each row scores one class on its {label} predictions. Instances counts the "
        f"ground-truth {subject_plural} of that class in the '{split}' split{source_note}. "
        f"A class with no ground truth in this split cannot be scored and is marked "
        f"'{ABSENT_CLASS_NOTE}'; that is not a score of zero."
    )
    lines.append('')
    lines.append('| Class | Instances | P | R | mAP50 | mAP50-95 |')
    lines.append('|---|---|---|---|---|---|')
    for cls in sorted(names):
        shown = class_display_name(cls)
        count = inst.get(cls, '?')
        d = pc.get(cls)
        if cls in absent or not isinstance(d, dict):
            lines.append(f'| {shown} | {count} | {ABSENT_CLASS_NOTE} | | | |')
            continue
        lines.append(f'| {shown} | {count} | {fmt_num(d.get(family_key(family, "precision")))} | '
                     f'{fmt_num(d.get(family_key(family, "recall")))} | '
                     f'{fmt_num(d.get(family_key(family, "map50")))} | '
                     f'{fmt_num(d.get(family_key(family, "map50_95")))} |')
    lines.append('')
    return lines


