def family_key(family, suffix):
    """Metrics-dict key for one score of one family, e.g. ('box', 'map50') -> 'box_map50'.

    Parameters:
        family: METRIC_FAMILY_MASK or METRIC_FAMILY_BOX.
        suffix: one of METRIC_SUFFIXES.
    Returns:
        The key string used in metrics['overall'] and metrics['per_class'][cls].
    """
    if family not in METRIC_FAMILIES:
        raise ValueError(f'unknown metric family {family!r}; expected one of {METRIC_FAMILIES}')
    if suffix not in METRIC_SUFFIXES:
        raise ValueError(f'unknown metric suffix {suffix!r}; expected one of {METRIC_SUFFIXES}')
    return f'{family}_{suffix}'


def metric_family(metrics):
    """Choose the metric family from the numbers a metrics dict carries.

    A segmentation run carries mask numbers (and box numbers beside them);
    a detector carries box numbers only. The choice comes from the values,
    never from a flag or a filename.

    Parameters:
        metrics: a dict shaped like extract_metrics() output, with 'overall'.
    Returns:
        METRIC_FAMILY_MASK when any overall mask score is present, else
        METRIC_FAMILY_BOX when any overall box score is present.
    Raises:
        ValueError when 'overall' is missing or malformed, or when neither
        family has a single number.
    """
    overall = metrics.get('overall') if isinstance(metrics, dict) else None
    if not isinstance(overall, dict):
        raise ValueError("metrics['overall'] is missing or not a mapping; cannot choose a metric family")
    for family in METRIC_FAMILIES:
        if any(overall.get(family_key(family, s)) is not None for s in METRIC_SUFFIXES):
            return family
    raise ValueError(
        'metrics carry neither box nor mask numbers (every overall value is None); '
        'the evaluation produced nothing to score'
    )


def _class_names_of(results):
    """Read the class-id to class-name mapping off a validation results object.

    Parameters:
        results: an ultralytics DetMetrics or SegmentMetrics (or a fake with .names).
    Returns:
        dict of int class id -> str class name.
    Raises:
        ValueError when the mapping is missing, empty, or has a non-integer id.
    """
    names = getattr(results, 'names', None)
    if not isinstance(names, dict) or not names:
        raise ValueError(
            'validation results carry no class names (results.names is empty or not a '
            'mapping); the model or data.yaml has no classes to score'
        )
    out = {}
    for cid, nm in names.items():
        try:
            out[int(cid)] = str(nm)
        except (TypeError, ValueError) as exc:
            raise ValueError(f'class id {cid!r} in results.names is not an integer') from exc
    return out


def _overall_family_scores(metric_obj, family):
    """Mean precision, recall, mAP50 and mAP50-95 of one ultralytics Metric.

    Parameters:
        metric_obj: results.box or results.seg.
        family: the family those scores belong to.
    Returns:
        dict of family_key(family, suffix) -> float.
    Raises:
        ValueError when the object lacks one of the mean attributes.
    """
    out = {}
    for attr, suffix in METRIC_ATTRIBUTES:
        if not hasattr(metric_obj, attr):
            raise ValueError(
                f'{family} metrics object has no {attr!r} attribute; expected an ultralytics Metric'
            )
        out[family_key(family, suffix)] = float(getattr(metric_obj, attr))
    return out


def _per_class_family_scores(metric_obj, names, family):
    """Per-class scores of one family, each result slot mapped back to its class.

    Ultralytics builds one result slot per class that has ground truth in the
    evaluated split and records the class id behind slot i in
    ap_class_index[i]; class_result(i) reads slot i. So slot i belongs to
    names[ap_class_index[i]], never to class id i.

    Parameters:
        metric_obj: results.box or results.seg.
        names: dict of class id -> class name.
        family: the family those scores belong to.
    Returns:
        (rows, present_ids): rows is dict class name -> {family_key: float};
        present_ids is the list of class ids that own a slot, in slot order.
    Raises:
        ValueError when ap_class_index is missing, points at an unknown class
        id, or names a slot the score arrays do not hold.
    """
    if not hasattr(metric_obj, 'ap_class_index'):
        raise ValueError(f'{family} metrics object has no ap_class_index; cannot map slots to classes')
    present_ids = [int(c) for c in metric_obj.ap_class_index]
    rows = {}
    for slot, class_id in enumerate(present_ids):
        if class_id not in names:
            raise ValueError(
                f'{family} result slot {slot} points at class id {class_id}, which is not '
                f'among the {len(names)} class names'
            )
        try:
            p, r, ap50, ap = metric_obj.class_result(slot)
        except IndexError as exc:
            raise ValueError(
                f'{family} per-class arrays hold no slot {slot} although ap_class_index '
                f'lists {len(present_ids)} slots: {exc}'
            ) from exc
        rows[names[class_id]] = {
            family_key(family, 'precision'): float(p),
            family_key(family, 'recall'): float(r),
            family_key(family, 'map50'): float(ap50),
            family_key(family, 'map50_95'): float(ap),
        }
    return rows, present_ids


def _per_class_instance_counts(results, names):
    """Ground-truth instance count per class in the evaluated split.

    The validator's own nt_per_class (a bincount over every target label,
    indexed by class id) is exact and is used when present. Otherwise the
    confusion matrix is summed per true-class column over every row,
    including the trailing background row that holds the missed instances;
    leaving that row out undercounts every class the model ever missed.

    Parameters:
        results: the validation results object.
        names: dict of class id -> class name.
    Returns:
        (counts, source): counts is dict class name -> int; source is one of
        INSTANCE_SOURCE_VALIDATOR or INSTANCE_SOURCE_CONFUSION_MATRIX.
    Raises:
        ValueError when neither source exists, the matrix is the wrong shape,
        or the matrix sums to zero (it is only filled when val runs with
        plots=True, so an empty one must not read as "no instances").
    """
    nt = getattr(results, 'nt_per_class', None)
    if nt is not None:
        arr = np.asarray(nt).ravel()
        counts = {nm: int(arr[cid]) if cid < len(arr) else 0 for cid, nm in names.items()}
        return counts, INSTANCE_SOURCE_VALIDATOR
    cm = getattr(results, 'confusion_matrix', None)
    mat = getattr(cm, 'matrix', None) if cm is not None else None
    if mat is None:
        raise ValueError(
            'no per-class instance source: results has neither nt_per_class nor a confusion matrix'
        )
    arr = np.asarray(mat)
    n_needed = max(names) + 2  # highest class id, plus one for the background column
    if arr.ndim != 2 or arr.shape[0] != arr.shape[1] or arr.shape[1] < n_needed:
        raise ValueError(
            f'confusion matrix shape {arr.shape} cannot hold {len(names)} classes '
            f'(highest id {max(names)}) plus a background column'
        )
    if arr.sum() == 0:
        raise ValueError(
            'confusion matrix sums to zero, so it was never filled (ultralytics fills it only '
            'when val runs with plots=True) and cannot supply per-class instance counts'
        )
    counts = {nm: int(arr[:, cid].sum()) for cid, nm in names.items()}
    return counts, INSTANCE_SOURCE_CONFUSION_MATRIX


def extract_metrics(val_out):
    """Turn ultralytics val output into a plain dict the renderers and the ledger read.

    Parameters:
        val_out: dict from run_val() with 'results', 'weights', 'data_yaml',
            'wall_seconds'.
    Returns:
        dict with 'class_names', 'overall' (every family key, None where the
        family does not exist), 'per_class' (only classes with ground truth),
        'absent_classes' (names with no ground truth in the split, so no
        score exists, which is not the same as a score of zero),
        'per_class_instances', 'per_class_instances_source', 'metric_family',
        'class_full_names' (class id to full name, only when at least one
        class token is a code), and 'fitness' plus 'speed_ms' when the
        results carry them.
    Raises:
        ValueError when the results carry no class names, neither metric
        family, or a slot that cannot be mapped to a class.
    """
    results = val_out['results']
    names = _class_names_of(results)
    box = getattr(results, 'box', None)
    seg = getattr(results, 'seg', None)
    if box is None and seg is None:
        raise ValueError('validation results carry neither box nor seg metrics; nothing to score')

    overall = {family_key(f, s): None for f in METRIC_FAMILIES for s in METRIC_SUFFIXES}
    per_class = {}
    present_ids = set()
    for family, metric_obj in ((METRIC_FAMILY_BOX, box), (METRIC_FAMILY_MASK, seg)):
        if metric_obj is None:
            continue
        overall.update(_overall_family_scores(metric_obj, family))
        rows, slot_ids = _per_class_family_scores(metric_obj, names, family)
        for nm, scores in rows.items():
            per_class.setdefault(nm, {}).update(scores)
        present_ids.update(slot_ids)
    absent = [names[cid] for cid in sorted(names) if cid not in present_ids]
    counts, source = _per_class_instance_counts(results, names)

    metrics = {
        'wall_seconds': val_out['wall_seconds'],
        'weights': val_out['weights'],
        'data_yaml': val_out['data_yaml'],
        'class_names': names,
        'overall': overall,
        'per_class': per_class,
        'absent_classes': absent,
        'per_class_instances': counts,
        'per_class_instances_source': source,
    }
    metrics['metric_family'] = metric_family(metrics)
    full_names = class_full_names_for(names)
    if full_names:
        metrics['class_full_names'] = full_names
    fitness = getattr(results, 'fitness', None)
    if fitness is not None:
        metrics['fitness'] = float(fitness)
    speed = getattr(results, 'speed', None)
    if isinstance(speed, dict):
        metrics['speed_ms'] = {k: float(v) for k, v in speed.items()}
    metrics.update(best_conf_fields(results))
    print(f"[eval] metric family: {metrics['metric_family']}; "
          f"{len(per_class)} of {len(names)} classes scored, {len(absent)} absent from the split; "
          f"instance counts from {source}")
    return metrics


_code_registry_cache = None


def _code_registry():
    """Load the module's code registry (code -> full name) once.

    Returns:
        dict of code -> name. Empty when CODE_REGISTRY_PATH does not exist.
    Raises:
        ValueError when the file exists but lacks the code and name columns.
    """
    global _code_registry_cache
    if _code_registry_cache is not None:
        return _code_registry_cache
    registry = {}
    if CODE_REGISTRY_PATH.is_file():
        with open(CODE_REGISTRY_PATH, newline='', encoding='utf-8') as fh:
            reader = _csv.DictReader(fh)
            header = reader.fieldnames or []
            missing = [c for c in CODE_REGISTRY_COLUMNS if c not in header]
            if missing:
                raise ValueError(f'code registry {CODE_REGISTRY_PATH} lacks columns {missing}')
            for row in reader:
                code = (row.get('code') or '').strip()
                name = (row.get('name') or '').strip()
                if code and name:
                    registry[code] = name
    else:
        print(f'[eval] code registry not found at {CODE_REGISTRY_PATH}; class codes are shown as codes')
    _code_registry_cache = registry
    return registry


# The staged dataset's own class names, set once per evaluation from the
# evaluated data.yaml. A staged box dataset (the fish photo set) names classes
# with tokens such as EPST_Dark that no species code table and no binomial
# rule resolves, so the dataset is the only place the full name exists.
_names_full_cache = {}


def set_names_full(mapping):
    """Set the per-run token to full-name map consulted before the code registry.

    Parameters:
        mapping: {class token: full name}; an empty mapping (or None) clears it.
            A blank token, and a blank name, are dropped rather than stored,
            so no class is ever shown with an empty name.
    Returns:
        None.
    Raises:
        TypeError when mapping is neither a mapping nor None.
    """
    global _names_full_cache
    if mapping is None:
        mapping = {}
    if not isinstance(mapping, dict):
        raise TypeError('set_names_full needs a mapping of class token to full name, '
                        f'got {type(mapping).__name__}')
    _names_full_cache = {str(k).strip(): str(v).strip() for k, v in mapping.items()
                         if str(k).strip() and str(v).strip()}


def _class_map_of(value, path, key):
    """One data.yaml class map as {class id: value}, from a mapping or a list.

    Ultralytics accepts both shapes: a mapping keyed by class id, and a list
    in class-id order.

    Parameters:
        value: the raw value read from the document, or None when absent.
        path: the file it came from, named in every error.
        key: the key it was read from, named in every error.
    Returns:
        dict of integer class id to the raw value; empty when value is None.
    Raises:
        ValueError when value is neither a mapping nor a list, or when a
        mapping key is not an integer.
    """
    if value is None:
        return {}
    if isinstance(value, list):
        return dict(enumerate(value))
    if not isinstance(value, dict):
        raise ValueError(f'{path} key {key} is a {type(value).__name__}, '
                         'not a mapping of class id to value or a list in class-id order')
    out = {}
    for raw_id, item in value.items():
        try:
            cid = int(str(raw_id).strip())
        except ValueError:
            raise ValueError(f'{path} key {key} has class id {raw_id!r}, which is not an integer') from None
        out[cid] = item
    return out


def names_full_from_data_yaml(path):
    """{class token: full name} from an evaluated dataset's data.yaml.

    A split dataset built from a staged dataset that carries a names table
    writes names_full (class id to full species name) beside names (class id
    to class token). The two are joined on the class id here, so every reader
    downstream works in tokens and never needs the ids.

    Parameters:
        path: the data.yaml of the evaluated split dataset.
    Returns:
        {token: full name}; empty when the file carries no names_full. An id
        that names does not carry, and a blank name, are left out.
    Raises:
        FileNotFoundError when path is not a file.
        OSError when the file exists but cannot be read.
        yaml.YAMLError when the file is not valid YAML.
        ValueError when the document, its names or its names_full cannot be
        read as a class map, naming the file and the key. A dataset that
        carries no names_full at all is never refused on the shape of its
        names map: the key is optional context for a chip, and every dataset
        built before it existed must still evaluate.
    """
    if not os.path.isfile(path):
        raise FileNotFoundError(f'data.yaml not found at {path}; the dataset names no classes')
    with open(path, encoding='utf-8') as fh:
        doc = yaml.safe_load(fh)
    if doc is None:
        doc = {}
    if not isinstance(doc, dict):
        raise ValueError(f'{path} does not hold a mapping, so it names no classes')
    if doc.get('names_full') is None:
        return {}
    names = _class_map_of(doc.get('names'), path, 'names')
    full = _class_map_of(doc.get('names_full'), path, 'names_full')
    joined = {}
    for cid, value in full.items():
        token = str(names.get(cid, '')).strip()
        name = str(value).strip()
        if token and name:
            joined[token] = name
    return joined


def class_full_names_for(names):
    """{class id: full name} for the class tokens that are codes.

    A token the evaluated dataset names, or the module's code registry knows,
    is a code: every reader of metrics.json shows the full name with the code
    beside it. A token written as a binomial is already its own name and is
    left out, because every reader expands it on its own and a code chip
    repeating it would say nothing new.

    Parameters:
        names: {class id: class token} as the validation results report it.
    Returns:
        {class id: full name}, empty when no token is a code.
    Raises:
        TypeError when names is neither a mapping nor None.
    """
    if names is None:
        names = {}
    if not isinstance(names, dict):
        raise TypeError('class_full_names_for needs a mapping of class id to class token, '
                        f'got {type(names).__name__}')
    resolved = {}
    for cid, token in names.items():
        tok = str(token or '').strip()
        full = _names_full_cache.get(tok) or _code_registry().get(tok)
        if tok and full:
            resolved[cid] = full
    return resolved


def _resolve_class_name(token):
    """Full name behind one class token, or None when nothing resolves it.

    The evaluated dataset's own names table wins (set_names_full), then the
    code registry (SS); a token written as a binomial (Acropora-cervicornis,
    Porites_astreoides) resolves to the same words separated by spaces.

    Parameters:
        token: the stripped class token.
    Returns:
        The full name string, or None.
    """
    full = _names_full_cache.get(token) or _code_registry().get(token)
    if full is None and BINOMIAL_TOKEN_RE.fullmatch(token):
        full = re.sub(r'[_-]', ' ', token)
    return full


def class_full_name(name):
    """Plain-text full name for one class, falling back to the token itself.

    Parameters:
        name: the class token from data.yaml.
    Returns:
        e.g. 'Siderastrea siderea' for 'SS'; 'sand' for 'sand'.
    """
    token = str(name or '').strip()
    if not token:
        return '?'
    full = _resolve_class_name(token)
    return full if full is not None else token


def _escaped_for_markdown_cell(text):
    """One name with its vertical bars escaped for a markdown table cell.

    The per-class table is a pipe table, so an unescaped vertical bar inside a
    name would open a new cell and shift every column of the row. A staged
    names table is a plain CSV a person edits, so a bar can reach this code.

    Parameters:
        text: the resolved name, already plain text.
    Returns:
        The same text with every '|' written as '\\|'.
    """
    return text.replace('|', r'\|')


def class_display_name(name):
    """Markdown for one class: the full name with the class token beside it.

    A token in the code registry (SS) or written as a binomial
    (Acropora-cervicornis) renders as the italic binomial with the token in
    a code span. A name that opens with a binomial and then adds qualifiers
    after a comma (a staged names table's "Epinephelus striatus, Nassau
    grouper, dark phase") italicises the binomial alone. Anything else stays a
    bare code span. A vertical bar in the name is escaped, so the per-class
    table keeps its columns; the token is not escaped, because it sits in a
    code span the report card parks before it splits a row.

    Parameters:
        name: the class token from data.yaml.
    Returns:
        A markdown string, e.g. '*Siderastrea siderea* (`SS`)'.
    """
    token = str(name or '').strip()
    if not token:
        return '`?`'
    full = _resolve_class_name(token)
    if full is None:
        return f'`{token}`'
    if BINOMIAL_NAME_RE.fullmatch(full):
        return f'*{_escaped_for_markdown_cell(full)}* (`{token}`)'
    prefix = BINOMIAL_PREFIX_RE.fullmatch(full)
    if prefix:
        return (f'*{_escaped_for_markdown_cell(prefix.group(1))}*'
                f'{_escaped_for_markdown_cell(prefix.group(2))} (`{token}`)')
    return f'{_escaped_for_markdown_cell(full)} (`{token}`)'


def class_display_html(name):
    """HTML for one class, same resolution as class_display_name.

    Parameters:
        name: the class token from data.yaml.
    Returns:
        Escaped HTML with the binomial in <i> (the binomial alone when the
        name adds qualifiers after a comma) and the token in a mono span.
    """
    token = str(name or '').strip()
    if not token:
        return '<span class="mono">?</span>'
    full = _resolve_class_name(token)
    if full is None:
        return f'<span class="mono">{_html_escape(token)}</span>'
    prefix = BINOMIAL_PREFIX_RE.fullmatch(full)
    if BINOMIAL_NAME_RE.fullmatch(full):
        shown = f'<i>{_html_escape(full)}</i>'
    elif prefix:
        shown = f'<i>{_html_escape(prefix.group(1))}</i>{_html_escape(prefix.group(2))}'
    else:
        shown = _html_escape(full)
    return f'{shown} <span class="mono">({_html_escape(token)})</span>'


