def gather_context(run_dir, dataset_dir):
    """Collect the run's training arguments, epoch count and split sizes for the report.

    Every piece is optional context: a missing or unreadable file is reported
    on the console and the key is left out, never silently defaulted.

    Parameters:
        run_dir: the training run folder (args.yaml, results.csv).
        dataset_dir: the split dataset folder.
    Returns:
        dict with 'run_dir', 'dataset_dir' and, when readable, 'train_args',
        'epochs_completed', 'results_csv', 'split_counts', 'best_epoch'.
    """
    ctx = {'run_dir': run_dir, 'dataset_dir': dataset_dir}

    args_yaml = os.path.join(run_dir, 'args.yaml')
    if os.path.isfile(args_yaml):
        try:
            with open(args_yaml) as f:
                ctx['train_args'] = yaml.safe_load(f)
        except (OSError, yaml.YAMLError) as exc:
            print(f'[eval] {args_yaml} unreadable, training arguments left out of the report: {exc}')

    res_csv = os.path.join(run_dir, 'results.csv')
    if os.path.isfile(res_csv):
        try:
            with open(res_csv) as f:
                rows = list(_csv.reader(f))
            ctx['epochs_completed'] = max(0, len(rows) - 1)
            ctx['results_csv'] = res_csv
        except (OSError, _csv.Error) as exc:
            print(f'[eval] {res_csv} unreadable, epoch count left out of the report: {exc}')

    # The same count the ledger records, from the one image-type list: a
    # split size printed in the report and in metrics.json must not disagree
    # with the ledger's because a folder holds WebP or TIFF images.
    for split in ('train', 'valid', 'test'):
        if os.path.isdir(os.path.join(dataset_dir, split, 'images')):
            ctx.setdefault('split_counts', {})[split] = _count_images(dataset_dir, split)

    # best epoch from results.csv (highest fitness proxy: highest mAP50-95(M))
    ctx['best_epoch'] = _find_best_epoch(os.path.join(run_dir, 'results.csv'))
    return ctx


def _find_best_epoch(results_csv):
    """Scan results.csv for the epoch with highest mAP50-95(M) (or (B) fallback)."""
    if not os.path.isfile(results_csv):
        return None
    try:
        with open(results_csv) as f:
            reader = _csv.reader(f)
            hdr = next(reader)
            hdr = [h.strip() for h in hdr]
            col = None
            for cand in ('metrics/mAP50-95(M)', 'metrics/mAP50-95(B)', 'metrics/mAP50(M)', 'metrics/mAP50(B)'):
                if cand in hdr:
                    col = hdr.index(cand)
                    break
            if col is None:
                return None
            best_val = -1.0
            best_ep = None
            ep_col = hdr.index('epoch') if 'epoch' in hdr else 0
            for row in reader:
                try:
                    v = float(row[col])
                    ep = int(float(row[ep_col]))
                    if v > best_val:
                        best_val = v
                        best_ep = ep
                except (ValueError, IndexError):
                    continue  # a partial or non-numeric row (an interrupted epoch) is skipped
            return best_ep
    except (OSError, _csv.Error, StopIteration) as exc:
        print(f'[eval] {results_csv} unreadable, best epoch left out of the report: {exc}')
        return None


