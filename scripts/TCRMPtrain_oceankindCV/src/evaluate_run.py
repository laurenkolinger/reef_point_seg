def _html_escape(s):
    """Minimal HTML-escape for text content."""
    if s is None:
        return ''
    return (
        str(s)
        .replace('&', '&amp;')
        .replace('<', '&lt;')
        .replace('>', '&gt;')
        .replace('"', '&quot;')
    )


AXIS_FAMILY_PLACEHOLDER = '{family}'


def _fill_family(text, key, family):
    """Substitute the metric family's wording into an axis note.

    Parameters:
        text: one axis-note sentence, possibly carrying AXIS_FAMILY_PLACEHOLDER.
        key: the note's key, for the error message.
        family: the run's metric family, or None when the note needs none.
    Returns:
        The sentence with the placeholder replaced by FAMILY_LABELS[family].
    Raises:
        ValueError when the sentence carries the placeholder and family is None.
    """
    if AXIS_FAMILY_PLACEHOLDER not in text:
        return text
    if family is None:
        raise ValueError(f'axis note {key!r} names the metric family, so family must be given')
    return text.replace(AXIS_FAMILY_PLACEHOLDER, FAMILY_LABELS[family])


def _axis_block_html(key, family=None):
    """Render the 4-line axis explanation block for a plot.

    Parameters:
        key: an AXIS_EXPLANATIONS_FULL key.
        family: the run's metric family, filled into the note's
            AXIS_FAMILY_PLACEHOLDER; required when the note carries one.
    Returns:
        The HTML block, or '' for an unknown key.
    Raises:
        ValueError when the note names the family and family is None.
    """
    e = AXIS_EXPLANATIONS_FULL.get(key)
    if not e:
        return ''
    filled = {name: _fill_family(e.get(name, ''), key, family)
              for name in ('what', 'x_axis', 'y_axis', 'read', 'connects')}
    read_full = (filled['read'] + ' ' + filled['connects']).strip()
    items = [
        ('What:', filled['what']),
        ('Horizontal axis:', filled['x_axis']),
        ('Vertical axis:', filled['y_axis']),
        ('How to read:', read_full),
    ]
    parts = ['<div class="axis-block">']
    for lbl, body in items:
        parts.append(
            f'<div class="axis-line"><span class="axis-label">{_html_escape(lbl)}</span>'
            f'<span class="axis-body">{_html_escape(body)}</span></div>'
        )
    parts.append('</div>')
    return fill_subject(''.join(parts))


def _file_uri(path):
    """file:// URI for a local path, made absolute, with spaces, hashes and
    non-ASCII characters percent-encoded so Chrome resolves it unchanged.

    Parameters:
        path: a file path, absolute or relative to the working directory.
    Returns:
        The URI string, e.g. file:///tmp/a%20b/c%23d.jpg.
    Raises:
        ValueError when path is empty.
    """
    if not path:
        raise ValueError('cannot build a file URI from an empty path')
    return Path(os.path.abspath(path)).as_uri()


def _img_src(path):
    """Image src attribute for a local file, or '' when there is no file.

    Parameters:
        path: the image path, or None or '' when the figure is absent.
    Returns:
        The file:// URI, or '' for no path.
    """
    if not path:
        return ''
    return _file_uri(path)


