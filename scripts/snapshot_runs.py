# --------------------------------------------------------------------------
# Constants
# --------------------------------------------------------------------------

_REPO = Path(__file__).resolve().parent.parent  # .../reef_point_seg/github_repo
DEFAULT_SOURCE = _REPO.parent / "inprocess"      # .../reef_point_seg/inprocess
DEFAULT_DEST = Path("/mnt/tear/vega_run_snapshots/daily")
DEFAULT_KEEP = 14

RUN_PREFIX = "run_"
FIXED_INCLUDED_SUBDIRS = (
    "_mask_registry",
    "_expert_id_library",
    "_composite",
    "_bbox",
    "_standalone",
)
MODELS_SUBDIR = "_models"

# --dest's final folder must have this name unless --allow-dest overrides
# the check: a guard against a typo'd or copy-pasted --dest quietly
# pointing this script's retention (which deletes old finished snapshots)
# at the wrong directory.
REQUIRED_DEST_BASENAME = "daily"

# Snapshot names that must never be pruned, no matter what --keep says or
# how they got inside dest. 20260926-222311 is a one-off copy made by hand
# on 2026-09-26, before this script existed; it carries no manifest.json
# of this script's own, so latest_finished_snapshot() also never chooses
# it as a --link-dest base (see that function).
PROTECTED_SNAPSHOT_NAMES = frozenset({"20260926-222311"})

STAMP_FORMAT = "%Y%m%d-%H%M%S"
STAMP_RE = re.compile(r"^\d{8}-\d{6}$")
PARTIAL_SUFFIX = ".partial"
LOCK_FILENAME = ".snapshot.lock"
MANIFEST_FILENAME = "manifest.json"

# A verify mismatch right after the copy is often a live writer (the
# orchestrator on port 5050, an open annotator) rewriting a file mid-rsync,
# not real corruption: re-running rsync into the SAME .partial picks up
# only what changed, so a second (or third) look usually clears it without
# re-copying the whole tree. Only after every attempt still mismatches does
# the run give up, leave the .partial for inspection, and prune nothing.
VERIFY_MAX_ATTEMPTS = 3
VERIFY_RETRY_WAIT_SECONDS = 60

# rsync's own exit code for "some files vanished before they could be
# transferred": a source file existed when rsync built its file list but
# was gone by the time it tried to read it. On this box that is almost
# always an annotator's own temp save file, not a real problem, so it is
# logged and treated as success rather than raised as SnapshotError.
RSYNC_VANISHED_SOURCE_EXIT_CODE = 24

# Substrings (checked case-insensitively) in rsync's stderr that mean the
# destination filesystem ran out of space, so that failure can be called
# out plainly instead of reported as just another opaque nonzero exit.
_DISK_FULL_STDERR_MARKERS = ("no space left", "enospc")

# Files whose byte-for-byte content is proven equal (sha256) between
# source and the fresh copy, on top of the file-count check that covers
# everything else. These four are what a lost or truncated write would
# hurt most: the per-project label and provenance records.
VERIFY_FILENAMES = frozenset({
    "segmentations.json",
    "label_provenance.csv",
    "project.json",
    "manifest.csv",
})

AST = timezone(timedelta(hours=-4))
_WRITE_BITS = stat.S_IWUSR | stat.S_IWGRP | stat.S_IWOTH


class SnapshotError(Exception):
    """Base class for every error this script raises on purpose."""


class SnapshotLockError(SnapshotError):
    """Another snapshot_runs.py run already holds the lock for this dest."""


class SnapshotVerificationError(SnapshotError):
    """The fresh copy did not match the source it was copied from."""


# --------------------------------------------------------------------------
# Test seams (see module docstring). Production code always reaches these
# through the module-level names below so a test can monkeypatch them
# without touching any other function.
# --------------------------------------------------------------------------

def _now_ast():
    """Return the current moment in Atlantic Standard Time (UTC-4).

    Returns:
        A timezone-aware datetime. Tests monkeypatch this name directly
        to control the snapshot stamp and to simulate two nights of the
        same fixture inside one process; production code never overrides
        it.
    """
    return datetime.now(AST)


def _sha256_of(path):
    """Compute the sha256 hex digest of a regular file.

    Parameters:
        path: Path to the file to hash. A symlink is read through (its
              target is hashed); every VERIFY_FILENAMES member has been a
              real output file, never a symlink, in every project this
              script has seen.

    Returns:
        The lowercase hex digest string.

    Raises:
        SnapshotError: if the file cannot be opened or read.
    """
    hasher = hashlib.sha256()
    try:
        with open(path, "rb") as handle:
            for chunk in iter(lambda: handle.read(1024 * 1024), b""):
                hasher.update(chunk)
    except OSError as exc:
        raise SnapshotError(f"could not read {path} to verify it: {exc}") from exc
    return hasher.hexdigest()


# --------------------------------------------------------------------------
# Validation
