def validate_source(source):
    """Raise a clear error if source cannot be copied from.

    Parameters:
        source: The path that should be the inprocess/ run directory.

    Raises:
        SnapshotError: if source does not exist, or exists but is not a
        directory (for example a stray file left at that path).
    """
    if not source.exists():
        raise SnapshotError(f"source does not exist: {source}")
    if not source.is_dir():
        raise SnapshotError(f"source is not a directory: {source}")


def validate_dest_parent(dest):
    """Raise a clear error if dest's parent directory is missing, which on
    this platform almost always means the destination drive (usually
    /mnt/tear) is not mounted right now.

    Parameters:
        dest: The snapshot destination directory. It need not exist yet
              itself (the first run creates it); only its parent must.

    Raises:
        SnapshotError: naming the missing parent and asking whether the
        drive is mounted.
    """
    parent = dest.parent
    if not parent.is_dir():
        raise SnapshotError(
            f"destination's parent directory does not exist: {parent} "
            "(is its drive mounted?)"
        )


def validate_dest_name(dest, allow_dest=False):
    """Refuse a --dest whose final folder is not named "daily", unless the
    caller explicitly opts out.

    Every real destination this script has ever run against is named
    .../vega_run_snapshots/daily. A --dest with a different final folder
    name is far more likely to be a typo or a copy-pasted path than a
    deliberate choice, and this script's retention logic deletes old
    finished snapshots inside whatever --dest it is given, so a silent
    wrong-directory run is worth refusing outright.

    Parameters:
        dest: The destination directory the CLI was given.
        allow_dest: True to skip this check because the operator has
                    confirmed the non-standard name on purpose (the CLI's
                    --allow-dest flag).

    Raises:
        SnapshotError: if dest's final folder is not named
        REQUIRED_DEST_BASENAME ("daily") and allow_dest is False.
    """
    if allow_dest:
        return
    dest = Path(dest)
    if dest.name != REQUIRED_DEST_BASENAME:
        raise SnapshotError(
            f"--dest's final folder must be named '{REQUIRED_DEST_BASENAME}', "
            f"got {dest.name!r} in {dest}; pass --allow-dest if this is deliberate"
        )


