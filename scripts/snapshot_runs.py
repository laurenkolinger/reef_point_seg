def sweep_stale_partials(dest):
    """Remove every *.partial directory in dest whose name (minus the
    suffix) matches the snapshot stamp pattern.

    A .partial directory only survives past the end of a run when that
    run crashed, or its last verify attempt still mismatched, before it
    could be renamed; the lock this function runs under proves no other
    run is using dest right now, so any *.partial found here is
    abandoned. A name that does not match the stamp pattern is left alone
    untouched, on the chance it is something else entirely.

    Parameters:
        dest: The snapshot destination directory.

    Returns:
        A list of the removed paths (possibly empty).
    """
    removed = []
    if not dest.is_dir():
        return removed
    for entry in sorted(dest.iterdir()):
        if entry.is_symlink() or not entry.name.endswith(PARTIAL_SUFFIX):
            continue
        stem = entry.name[: -len(PARTIAL_SUFFIX)]
        if not STAMP_RE.fullmatch(stem) or not entry.is_dir():
            continue
        _restore_tree_write(entry)
        shutil.rmtree(entry)
        removed.append(entry)
    return removed


def _remove_write_bit(path):
    """Remove every write bit (owner, group, other) from one file or
    directory. A symlink is skipped outright: permission bits on the link
    itself are meaningless on Linux, and changing them would follow the
    link to whatever it points at, possibly outside the snapshot."""
    if path.is_symlink():
        return
    mode = os.stat(path, follow_symlinks=False).st_mode
    os.chmod(path, mode & ~_WRITE_BITS)


def _chmod_tree_read_only(root):
    """Remove every write bit under root, in every directory and file,
    without ever following a symlink.

    Parameters:
        root: The finished snapshot directory to write-protect.
    """
    for current_dir, dirnames, filenames in os.walk(root, followlinks=False):
        current = Path(current_dir)
        for name in filenames:
            _remove_write_bit(current / name)
        for name in dirnames:
            _remove_write_bit(current / name)
    _remove_write_bit(root)


def _restore_tree_write(root):
    """Add the owner write bit back to every directory under root so
    shutil.rmtree can delete it.

    Deleting a directory entry (file or subdirectory) needs write
    permission on its containing directory, not on the entry itself, so
    only directories are touched here; files never need their own write
    bit restored. A symlinked directory is skipped, never chmod'd and
    never descended into, so restoring permissions for a deletion can
    never reach anything outside root.

    Parameters:
        root: The directory tree that is about to be deleted.

    Raises:
        SnapshotError: if root itself is a symlink (refuses outright
        rather than risk restoring permissions through it).
    """
    if root.is_symlink():
        raise SnapshotError(f"refusing to restore permissions through a symlink: {root}")
    for current_dir, _dirnames, _filenames in os.walk(root, topdown=True, followlinks=False):
        current = Path(current_dir)
        if not current.is_symlink():
            mode = os.stat(current, follow_symlinks=False).st_mode
            os.chmod(current, mode | stat.S_IWUSR)


def list_finished_snapshots(dest):
    """List every finished snapshot directly under dest, oldest first.

    A finished snapshot is a real directory, never a symlink, whose name
    matches the stamp pattern exactly. Nothing else in dest, including a
    same-looking symlink or a *.partial directory, is ever selected as a
    rotation candidate by this or any other function in this script.

    Parameters:
        dest: The snapshot destination directory.

    Returns:
        A list of Path objects sorted oldest-to-newest by name (the fixed
        width YYYYMMDD-HHMMSS format sorts lexically in time order).
    """
    if not dest.is_dir():
        return []
    found = [
        entry for entry in dest.iterdir()
        if not entry.is_symlink() and entry.is_dir() and STAMP_RE.fullmatch(entry.name)
    ]
    return sorted(found, key=lambda p: p.name)


def latest_finished_snapshot(dest):
    """The most recent finished snapshot in dest that has its own
    manifest.json, or None if there is not one yet.

    A finished-looking directory without manifest.json is skipped rather
    than trusted as a --link-dest base. That covers the one-off snapshot
    20260926-222311 (made by hand, before this script existed, so it has
    no manifest.json of this script's own) and, defensively, a directory
    left behind by a crash between write_manifest and the rename in some
    future version of this script. rsync's --link-dest quick check trusts
    whatever files it finds there; a directory this script did not fully
    finish writing should never be that trusted.

    Parameters:
        dest: The snapshot destination directory.

    Returns:
        A Path, or None if dest holds no finished, manifested snapshot
        yet (including the very first run).
    """
    for candidate in reversed(list_finished_snapshots(dest)):
        if (candidate / MANIFEST_FILENAME).is_file():
            return candidate
    return None


def prune_old_snapshots(dest, keep):
    """Delete the oldest finished snapshots beyond the newest `keep`.

    Parameters:
        dest: The snapshot destination directory.
        keep: How many of the newest finished snapshots to retain. Must
              be at least 1: a --keep of 0 would delete every snapshot on
              its own next run, which nightly retention never means.

    Returns:
        The list of removed Path objects, oldest first (possibly empty).

    Raises:
        SnapshotError: if keep is less than 1, or (defense in depth,
        should list_finished_snapshots ever be bypassed) a removal
        candidate is a symlink, sits outside dest, its name does not
        match the stamp pattern, or its name is in
        PROTECTED_SNAPSHOT_NAMES.
    """
    if keep < 1:
        raise SnapshotError(f"--keep must be at least 1, got {keep}")
    # A name in PROTECTED_SNAPSHOT_NAMES never counts toward `keep` and is
    # never a removal candidate: it is invisible to this rotation entirely.
    finished = [p for p in list_finished_snapshots(dest) if p.name not in PROTECTED_SNAPSHOT_NAMES]
    if len(finished) <= keep:
        return []
    to_remove = finished[: len(finished) - keep]
    removed = []
    for candidate in to_remove:
        if candidate.name in PROTECTED_SNAPSHOT_NAMES:
            raise SnapshotError(f"refusing to prune a protected snapshot name: {candidate}")
        if candidate.is_symlink():
            raise SnapshotError(f"refusing to prune a symlink: {candidate}")
        if candidate.parent != dest:
            raise SnapshotError(f"refusing to prune outside dest: {candidate}")
        if not STAMP_RE.fullmatch(candidate.name):
            raise SnapshotError(f"refusing to prune a non-stamp name: {candidate}")
        _restore_tree_write(candidate)
        shutil.rmtree(candidate)
        removed.append(candidate)
    return removed


