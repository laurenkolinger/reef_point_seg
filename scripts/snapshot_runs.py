def discover_source_paths(source, include_models):
    """List the top-level source directories one snapshot copies.

    Parameters:
        source: The inprocess/ root (or a fixture standing in for it).
        include_models: Also include _models (trained weights) when True.

    Returns:
        A sorted list of Path objects, each an existing, non-symlinked
        directory directly under source. Every run_* project directory is
        included; a missing optional platform directory (for example a
        fresh checkout with no _standalone yet) is silently skipped
        rather than treated as an error, since its absence is normal on a
        young checkout. A top-level entry that is itself a symlink is
        skipped: nothing in the real data is ever laid out that way, and
        following one could copy from, or chmod, somewhere unexpected.

    Raises:
        SnapshotError: if source is not a directory.
    """
    validate_source(source)
    paths = []
    for entry in sorted(source.iterdir()):
        if entry.is_symlink():
            continue
        if entry.is_dir() and entry.name.startswith(RUN_PREFIX):
            paths.append(entry)
    for name in FIXED_INCLUDED_SUBDIRS:
        candidate = source / name
        if candidate.is_dir() and not candidate.is_symlink():
            paths.append(candidate)
    if include_models:
        candidate = source / MODELS_SUBDIR
        if candidate.is_dir() and not candidate.is_symlink():
            paths.append(candidate)
    return paths


def _count_files(root):
    """Count filesystem entries that are not directories under root.

    Parameters:
        root: Directory to count. A symlinked directory encountered along
              the way is counted as one entry and never descended into,
              on both the source and the destination side alike, so the
              two counts stay comparable.

    Returns:
        The total file count, or 0 if root does not exist (a fixed
        subdirectory such as _standalone is optional).
    """
    if not root.exists():
        return 0
    total = 0
    for _current, _dirnames, filenames in os.walk(root, followlinks=False):
        total += len(filenames)
    return total


