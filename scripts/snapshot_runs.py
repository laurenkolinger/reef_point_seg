def _verify_with_retries(paths, partial, prev, log, verify_retry_wait_seconds):
    """Verify a copy, retrying the rsync into the same .partial when a
    mismatch looks transient.

    A mismatch right after the initial copy is often a live writer (the
    orchestrator on port 5050, an open annotator) rewriting a file while
    rsync was mid-copy, not real corruption. Re-running rsync into the
    same .partial, against the same --link-dest, only re-transfers what
    still differs, so a second or third look usually clears it without
    re-copying the whole tree.

    Parameters:
        paths: The source directories this snapshot copied.
        partial: The .partial destination directory to verify, and, on a
                 retry, to re-copy into.
        prev: The previous finished snapshot rsync hard-links against.
              The same value is used for every retry, per VERIFY_MAX_ATTEMPTS.
        log: The progress-logging callable from take_snapshot. Each failed
             attempt is logged with the mismatched files it found.
        verify_retry_wait_seconds: Seconds to wait before each retry copy.
                                   0 skips the wait (tests use this).

    Returns:
        A (counts, verified_files, attempts_used) tuple from whichever
        attempt finally verified clean.

    Raises:
        SnapshotVerificationError: the last attempt's mismatch, if every
        one of VERIFY_MAX_ATTEMPTS attempts still found one.
    """
    last_error = None
    for attempt in range(1, VERIFY_MAX_ATTEMPTS + 1):
        try:
            counts = verify_counts(paths, partial)
            verified_files = verify_hashes(paths, partial)
            return counts, verified_files, attempt
        except SnapshotVerificationError as exc:
            last_error = exc
            log(f"  verify attempt {attempt}/{VERIFY_MAX_ATTEMPTS} found a mismatch: {exc}")
            if attempt == VERIFY_MAX_ATTEMPTS:
                break
            log(f"  waiting {verify_retry_wait_seconds}s, then re-copying into the same "
                ".partial before verifying again")
            if verify_retry_wait_seconds > 0:
                time.sleep(verify_retry_wait_seconds)
            run_rsync(paths, partial, prev, log=log)
    raise last_error


def take_snapshot(source, dest, keep=DEFAULT_KEEP, include_models=False, dry_run=False,
                   verify_retry_wait_seconds=VERIFY_RETRY_WAIT_SECONDS, log=print):
    """Run one full snapshot cycle: discover, lock, copy, verify (with
    bounded retry), finish, prune.

    Parameters:
        source: The inprocess/ root to copy from. Read-only to this
                function: nothing under it is ever written, moved,
                deleted or chmod'd.
        dest: The directory finished and in-progress snapshots live
              under.
        keep: How many finished snapshots to retain.
        include_models: Also copy _models (trained weights).
        dry_run: Print the plan and touch nothing on disk (not even the
                 lock file).
        verify_retry_wait_seconds: Seconds to wait between a failed verify
                                   and the next retry copy. Defaults to
                                   VERIFY_RETRY_WAIT_SECONDS (60); tests
                                   pass 0 so a forced mismatch does not
                                   really sleep.
        log: A callable taking one string, for the "Step N complete"
             progress checkpoints. Defaults to print.

    Returns:
        A dict: stamp, final_dir (None on a dry run), counts,
        verified_files, pruned (list of removed paths), dry_run.

    Raises:
        SnapshotError (or a subclass): source missing, dest's parent
        missing, the lock already held, rsync failing (other than a
        vanished-source warning or a retried mismatch), or every one of
        VERIFY_MAX_ATTEMPTS verify attempts finding a mismatch. In every
        one of the last three cases the .partial directory (if any) is
        left in place, until the next run's stale-partial sweep, and
        nothing is pruned this run.
    """
    source = Path(source)
    dest = Path(dest)

    paths = discover_source_paths(source, include_models)
    log(f"Step 1 complete: source validated, {len(paths)} top-level path(s) to copy from {source}")

    if dry_run:
        prev = latest_finished_snapshot(dest)
        finished = list_finished_snapshots(dest)
        would_prune = finished[: max(0, len(finished) - keep)]
        log("DRY RUN: nothing was copied, deleted or chmod'd.")
        log(f"  would copy: {[p.name for p in paths] or '(nothing; empty source)'}")
        log(f"  would link-dest against: {prev.name if prev else '(none; first snapshot)'}")
        log(f"  would prune: {[p.name for p in would_prune] or '(nothing)'}")
        return {"stamp": None, "final_dir": None, "counts": {}, "verified_files": [],
                "pruned": [], "dry_run": True}

    validate_dest_parent(dest)
    dest.mkdir(exist_ok=True)

    with SnapshotLock(dest):
        log("Step 2 complete: lock acquired")
        stale = sweep_stale_partials(dest)
        if stale:
            log(f"  swept {len(stale)} stale .partial dir(s) left by a crashed earlier run")

        prev = latest_finished_snapshot(dest)
        moment = _now_ast()
        stamp = moment.strftime(STAMP_FORMAT)
        partial = dest / f"{stamp}{PARTIAL_SUFFIX}"
        if partial.exists():
            raise SnapshotError(f"a .partial for this exact stamp already exists: {partial}")

        run_rsync(paths, partial, prev, log=log)
        log(f"Step 3 complete: rsync finished into {partial}")

        counts, verified_files, attempts_used = _verify_with_retries(
            paths, partial, prev, log, verify_retry_wait_seconds
        )
        total_files = sum(c["dest"] for c in counts.values())
        log(f"Step 4 complete: verified {total_files} file(s) by count, "
            f"{len(verified_files)} by content (attempt {attempts_used}/{VERIFY_MAX_ATTEMPTS})")

        # Manifest written into the .partial BEFORE the rename: see
        # write_manifest's own docstring for why this order matters.
        write_manifest(partial, stamp, moment, source, paths, include_models, prev,
                        counts, verified_files)
        final_dir = dest / stamp
        partial.rename(final_dir)
        _chmod_tree_read_only(final_dir)
        log(f"Step 5 complete: {final_dir} finished, manifested and made read-only")

        pruned = prune_old_snapshots(dest, keep)
        log(f"Step 6 complete: retention kept {len(list_finished_snapshots(dest))}, "
            f"pruned {len(pruned)}")

    return {"stamp": stamp, "final_dir": final_dir, "counts": counts,
            "verified_files": verified_files, "pruned": pruned, "dry_run": False}


