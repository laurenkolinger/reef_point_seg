def parse_args(argv=None):
    """Parse command-line arguments.

    Parameters:
        argv: Argument list, or None to use sys.argv[1:].

    Returns:
        The parsed argparse.Namespace.
    """
    parser = argparse.ArgumentParser(
        description="Nightly point-in-time copy of reef_point_seg's inprocess/ run data."
    )
    parser.add_argument("--source", default=str(DEFAULT_SOURCE),
                         help=f"Directory to copy from. Default: {DEFAULT_SOURCE}")
    parser.add_argument("--dest", default=str(DEFAULT_DEST),
                         help=f"Directory dated snapshots are written under. Default: {DEFAULT_DEST}")
    parser.add_argument("--keep", type=int, default=DEFAULT_KEEP,
                         help=f"Number of finished snapshots to retain. Default: {DEFAULT_KEEP}")
    parser.add_argument("--include-models", action="store_true",
                         help="Also copy inprocess/_models (trained weights). Off by default.")
    parser.add_argument("--allow-dest", action="store_true",
                         help=f"Allow a --dest whose final folder is not named "
                              f"'{REQUIRED_DEST_BASENAME}'. Off by default.")
    parser.add_argument("--dry-run", action="store_true",
                         help="Print what would be copied and pruned; write nothing.")
    return parser.parse_args(argv)


def main(argv=None):
    """Parse arguments, validate them, run one snapshot cycle, and report
    the result. Entry point for the cron job and for manual runs.

    Returns:
        0 on success (including a clean dry run); 1 if a SnapshotError
        (or subclass) was raised.
    """
    args = parse_args(argv)
    try:
        validate_dest_name(args.dest, args.allow_dest)
        validate_source(Path(args.source))
        result = take_snapshot(
            source=args.source,
            dest=args.dest,
            keep=args.keep,
            include_models=args.include_models,
            dry_run=args.dry_run,
        )
    except SnapshotError as exc:
        print(f"snapshot_runs.py: {exc}", file=sys.stderr)
        return 1

    if not result["dry_run"]:
        print(f"snapshot_runs.py: done. {result['final_dir']}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
