#!/usr/bin/env python3
"""Module: snapshot_runs.py

Purpose
-------
Nightly point-in-time copy of reef_point_seg's live run data so annotation
and training work survives an accidental delete, a bad merge, or a crashed
process. Copies every run_* project directory plus the platform-wide
_mask_registry, _expert_id_library, _composite, _bbox and _standalone
directories out of the module's inprocess/ tree into a dated, read-only
snapshot under /mnt/tear/vega_run_snapshots/daily/. Uses rsync --link-dest
against the newest previous finished snapshot so a file unchanged since
last night costs no extra disk space: it is hard-linked, not copied.
Keeps the newest 14 finished snapshots and prunes older ones, but only
after the new snapshot has verified clean; a failed or unverified run
leaves its partial copy in place for inspection and prunes nothing.

A verify mismatch is not necessarily corruption: reef_point_seg's own
orchestrator or an open annotator can rewrite a file (most often
_mask_registry/manifest.csv), or delete its own temp save file, while the
copy is in flight. On a mismatch the script re-runs rsync into the same
.partial (against the same --link-dest, with --delete so a file that
vanished from source since the last pass is removed from the .partial
too, not left behind as a permanent phantom mismatch) and re-verifies, up
to VERIFY_MAX_ATTEMPTS (3) times, waiting VERIFY_RETRY_WAIT_SECONDS (60)
between attempts. Each failed attempt is logged with the files that
mismatched. Only after the last attempt still mismatches does the run
give up, leave the .partial, and prune nothing. Separately, rsync exiting
with code 24 (some source files vanished mid-transfer, most often a temp
save file, before rsync could even read them) is logged as a warning, not
treated as a failure, and the run proceeds straight to verification. A
genuine disk-full failure (ENOSPC, or "No space left" in rsync's stderr)
is logged explicitly as "disk full" before the error is raised.

Every --dest must end in a folder literally named "daily" unless
--allow-dest is passed; this catches a typo'd or copy-pasted --dest
before its retention logic (which deletes old finished snapshots) can run
against the wrong directory. A fixed PROTECTED_SNAPSHOT_NAMES set
(currently just the one-off snapshot 20260926-222311, made by hand before
this script existed) is never pruned even if it somehow ends up inside
dest.

_models (trained model weights) is excluded by default. Measured at
build time it was 7.5 GB, as large as every run directory combined, and
7.2 GB of that was one directory of checkpoints. A trained model can be
regenerated by retraining from the surviving dataset and labels; a human
annotation cannot be regenerated at all, so this script's default budget
protects the annotations first. Pass --include-models to back it up too.

Symlinks in the source (for example a project's all_images/*.jpeg
pointing into routed_input/raw, or step1's all_points.csv pointing
outside inprocess entirely) are copied AS SYMLINKS: rsync -a's default
link handling, never followed and never dereferenced. Every chmod in
this script skips symlinks outright, so a permission change can never
reach a file the symlink happens to point at outside the snapshot.

Inputs
------
--source PATH        Directory to copy from. Default: the module's
                      inprocess/ run directory (reef_point_seg/inprocess,
                      resolved from this file's own location).
--dest PATH           Directory dated snapshots are written under.
                      Default: /mnt/tear/vega_run_snapshots/daily/.
--keep N              How many finished snapshots to retain. Default 14.
--include-models      Also copy inprocess/_models. Off by default (see
                      Purpose above).
--allow-dest          Allow a --dest whose final folder is not named
                      "daily". Off by default; see Purpose above.
--dry-run             Print what would be copied and pruned; write, move,
                      delete or chmod nothing.

Outputs
-------
<dest>/<YYYYMMDD-HHMMSS>/         A read-only (chmod a-w) copy of the
                                  included source directories, named by
                                  the Atlantic Standard Time (UTC-4)
                                  moment the snapshot started, holding its
                                  own manifest.json (written before this
                                  directory gets its final name; see
                                  <stamp>.partial/ below).
<dest>/<stamp>/manifest.json      Stamp, source, included directories,
                                  file counts, total bytes, and the list
                                  of files whose sha256 was checked
                                  against source.
<dest>/<stamp>.partial/           A snapshot in progress, or one whose
                                  last verify attempt still mismatched.
                                  Renamed to <stamp>/ only after
                                  verification passes. A failed run's
                                  .partial is left in place so it can be
                                  inspected, but only until the NEXT run:
                                  sweep_stale_partials() removes any
                                  leftover .partial, once it holds the
                                  lock, at the start of every run. Check
                                  it (and the run's log line) before the
                                  next scheduled attempt.
<dest>/.snapshot.lock             An empty lock file; holds an flock for
                                  the life of one run so two snapshot
                                  runs can never write into the same
                                  dest at once.

Two module-level seams exist only for scripts/tests/test_snapshot_runs.py
and are not part of the CLI: tests monkeypatch _now_ast to control the
stamp (so two "nights" of one fixture can run inside one process), and
they exercise a verification failure by monkeypatching _sha256_of rather
than by adding a hidden flag to production code.

Run with /usr/bin/python3 scripts/snapshot_runs.py [options] (stdlib
only; no virtualenv needed).
"""

