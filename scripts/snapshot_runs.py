def verify_counts(paths, dest_root):
    """Confirm the destination has exactly as many files as the source,
    directory by directory.

    Parameters:
        paths: The source directories this snapshot copied (as returned
               by discover_source_paths).
        dest_root: The (still-partial) destination directory the source
                   directories were rsynced into.

    Returns:
        A dict mapping each source directory's name to
        {"source": n, "dest": n}.

    Raises:
        SnapshotVerificationError: if any pair of counts disagrees,
        naming every mismatched directory and its two counts in one
        message.
    """
    counts = {}
    mismatches = []
    for source_path in paths:
        name = source_path.name
        source_count = _count_files(source_path)
        dest_count = _count_files(dest_root / name)
        counts[name] = {"source": source_count, "dest": dest_count}
        if source_count != dest_count:
            mismatches.append(f"{name}: source has {source_count}, copy has {dest_count}")
    if mismatches:
        raise SnapshotVerificationError("file count mismatch after copy: " + "; ".join(mismatches))
    return counts


def verify_hashes(paths, dest_root):
    """Confirm every segmentations.json, label_provenance.csv,
    project.json and manifest.csv copied byte-for-byte identical to its
    source.

    Parameters:
        paths: The source directories this snapshot copied.
        dest_root: The (still-partial) destination directory to compare
                   against.

    Returns:
        A sorted list of the relative paths (as strings, relative to the
        inprocess root) that were checked, for the manifest.

    Raises:
        SnapshotVerificationError: naming every file that is missing from
        the copy or whose sha256 differs from its source.
    """
    checked = []
    mismatches = []
    for source_path in paths:
        for current_dir, _dirnames, filenames in os.walk(source_path, followlinks=False):
            for filename in filenames:
                if filename not in VERIFY_FILENAMES:
                    continue
                source_file = Path(current_dir) / filename
                if source_file.is_symlink():
                    continue  # never seen in practice; a real output file, not a link
                rel = source_file.relative_to(source_path.parent)
                dest_file = dest_root / rel
                if not dest_file.is_file():
                    mismatches.append(f"{rel}: missing from copy")
                    continue
                if _sha256_of(source_file) != _sha256_of(dest_file):
                    mismatches.append(f"{rel}: sha256 differs")
                    continue
                checked.append(str(rel))
    if mismatches:
        raise SnapshotVerificationError("content mismatch after copy: " + "; ".join(mismatches))
    return sorted(checked)


# --------------------------------------------------------------------------
# Locking
# --------------------------------------------------------------------------

class SnapshotLock:
    """Holds an exclusive, non-blocking flock on <dest>/.snapshot.lock for
    the life of one snapshot run, so a second concurrent run refuses
    cleanly instead of writing into the same .partial directory."""

    def __init__(self, dest):
        self._path = dest / LOCK_FILENAME
        self._handle = None

    def __enter__(self):
        self._handle = open(self._path, "a+")
        try:
            fcntl.flock(self._handle.fileno(), fcntl.LOCK_EX | fcntl.LOCK_NB)
        except OSError as exc:
            self._handle.close()
            self._handle = None
            raise SnapshotLockError(
                f"another snapshot_runs.py run holds the lock at {self._path}"
            ) from exc
        return self

    def __exit__(self, exc_type, exc, tb):
        if self._handle is not None:
            fcntl.flock(self._handle.fileno(), fcntl.LOCK_UN)
            self._handle.close()
        return False


