def _stderr_indicates_disk_full(stderr):
    """True if rsync's stderr text looks like the destination ran out of
    space (ENOSPC), checked case-insensitively against
    _DISK_FULL_STDERR_MARKERS.

    Parameters:
        stderr: The rsync process's captured stderr text.

    Returns:
        True if a known disk-full marker appears anywhere in stderr.
    """
    lowered = stderr.lower()
    return any(marker in lowered for marker in _DISK_FULL_STDERR_MARKERS)


def run_rsync(paths, dest_partial, link_dest, log=print):
    """Copy every directory in paths into dest_partial with rsync -a.

    Parameters:
        paths: Source directories to copy; each becomes a same-named
               subdirectory of dest_partial. An empty list is valid (an
               empty source) and only creates dest_partial.
        dest_partial: The .partial destination directory. --delete keeps
                      it in sync with source on a retry: a file this
                      script already copied here that has since vanished
                      from source (most often an annotator's own temp
                      save file cleaned up between attempts) is removed
                      from dest_partial too, instead of staying behind as
                      a phantom extra file that would make the file-count
                      check mismatch on every subsequent attempt even
                      though nothing is actually wrong. --delete only
                      ever removes files inside dest_partial itself; it
                      never touches link_dest or source.
        link_dest: The previous finished snapshot to hard-link unchanged
                   files against, or None for the first-ever snapshot.
        log: A callable taking one string. Used only to warn when rsync
             reports vanished source files (exit code
             RSYNC_VANISHED_SOURCE_EXIT_CODE) instead of failing.

    Raises:
        SnapshotError: if rsync exits nonzero with any code other than
        RSYNC_VANISHED_SOURCE_EXIT_CODE. A stderr mentioning ENOSPC or
        "No space left" is called out explicitly as "disk full" in the
        log and in the raised error's message.
    """
    dest_partial.mkdir(parents=True, exist_ok=True)
    if not paths:
        return
    # -a without perms/owner/group: this script chmods every finished snapshot
    # read-only (_chmod_tree_read_only), and rsync -a's default behaviour is
    # to make each new copy's permissions match the SOURCE's. Once a snapshot
    # has been write-protected, that would make every following night's copy
    # of an unchanged file look "different" from its --link-dest candidate
    # (whose permissions are now read-only, not the source's normal mode),
    # so rsync would fall back to a fresh copy instead of a hard link, and
    # nightly retention would cost full disk space instead of nearly none.
    # Recursion, symlinks, times and device/special files are still preserved.
    # --delete: see the dest_partial parameter above.
    command = ["rsync", "-a", "--delete", "--no-perms", "--no-owner", "--no-group"]
    if link_dest is not None:
        command.append(f"--link-dest={link_dest}")
    command.extend(str(p) for p in paths)
    command.append(str(dest_partial) + os.sep)
    result = subprocess.run(command, capture_output=True, text=True)
    if result.returncode == RSYNC_VANISHED_SOURCE_EXIT_CODE:
        log(f"  rsync warning: exit {RSYNC_VANISHED_SOURCE_EXIT_CODE} (some source "
            "file(s) vanished mid-transfer, most likely a temp save file); "
            "continuing to verification")
        return
    if result.returncode != 0:
        if _stderr_indicates_disk_full(result.stderr):
            log(f"  rsync failed: disk full (exit {result.returncode})")
            raise SnapshotError(
                f"rsync exited {result.returncode} (disk full): {result.stderr.strip()}"
            )
        raise SnapshotError(f"rsync exited {result.returncode}: {result.stderr.strip()}")


