def _tree_size_bytes(root):
    """Total size in bytes of every file under root.

    Uses each symlink's own size, never its target's, so a snapshot's
    reported size can never be inflated (or a read attempted) by
    following a symlink to a file outside the snapshot.

    Parameters:
        root: The directory tree to size.

    Returns:
        The total byte count.
    """
    total = 0
    for current_dir, _dirnames, filenames in os.walk(root, followlinks=False):
        for name in filenames:
            path = Path(current_dir) / name
            try:
                total += os.stat(path, follow_symlinks=False).st_size
            except OSError:
                continue
    return total


def write_manifest(snapshot_dir, stamp, created_at, source, paths, include_models,
                    link_dest, counts, verified_files):
    """Write manifest.json describing one snapshot.

    Called on the .partial directory BEFORE it is renamed to its final
    name (see take_snapshot), so a crash between this write and the
    rename leaves, at worst, a .partial that already has its own
    manifest.json; sweep_stale_partials() removes the whole thing on the
    next run either way. This ordering is what makes it impossible for a
    finished (non-.partial) snapshot to exist without a manifest.json of
    its own.

    Parameters:
        snapshot_dir: The (still-partial) directory to write into.
        stamp: The snapshot's own name, YYYYMMDD-HHMMSS in AST.
        created_at: The AST datetime the run started (same moment stamp
                    was derived from).
        source: The inprocess/ root this snapshot was copied from.
        paths: The source directories that were included.
        include_models: Whether _models was part of this run.
        link_dest: The previous snapshot rsync hard-linked against, or
                   None for the first-ever snapshot.
        counts: The per-directory file-count dict from verify_counts.
        verified_files: The relative paths whose sha256 was checked.
    """
    manifest = {
        "stamp": stamp,
        "created_at": created_at.isoformat(),
        "source": str(source),
        "included_top_level": [p.name for p in paths],
        "include_models": include_models,
        "link_dest": link_dest.name if link_dest else None,
        "file_counts": counts,
        "total_bytes": _tree_size_bytes(snapshot_dir),
        "verified_files": verified_files,
    }
    (snapshot_dir / MANIFEST_FILENAME).write_text(json.dumps(manifest, indent=2, sort_keys=True) + "\n")


